// config.networkSounds, Krunker v10.0.4 (deob-10.0.4.js:18263; the config key :19904): the sound
// list Krunker puts on the wire as an index. The server sends `networkSounds.indexOf(name)`: "s"
// PLAYER_SOUND / "so" PLAY_SOUND / "sso" STOP_SOUND from game.playSound / playerSound (:216763,
// :197936 getSoundIndex), the "6" GET_KILL kill sound (:198642), config.taunts' id (:21244,
// :198329). The client plays `networkSounds[i]` unless the message flags a user asset or carries a
// name (`isNumber(i) && !isAsset ? networkSounds[i] : i`, :216733, :257755-257767, :259303).
// Trigger sounds go by name (emitterSounds, triggers.h) and KrunkScript's GAME.SOUND.play2D / play3D /
// stop take user asset ids (isAsset true, :210468-210510; client/src/ks/ks_sound.c): neither is a
// network id. KrunkNative's own server -> client NetSoundPacket carries the name; ids are the official
// link's wire (client/src/net/krunker_link.c through krunker_sounds.h).
//
// The table is ids and names only: the bundle gives an entry no volume or flag of its own. A
// sound's volume channel is SOUND.soundCats by name (client/src/audio.c, :224701), its file
// assets/sound/<name>.mp3 (getSound: assetsUrl("/sound/" + name + ".mp3"), :225205). The table is
// generated by tools/krunker/extract_sounds.py into shared/src/rules/v10/network_sounds_v10.c and
// checked by shared/tests/network_sounds_test.c.
//
// One id space since v3.1.1: each version only appended (v3.1.1 51 names, v7.1.4 265, v10.0.3 399).
// v7.1.4's list is v10.0.3's first 265 unchanged; v3.1.1's first 51 differ only at id 32 ("weapon_17"
// a second time, which indexOf never sent: v3 sent 22; "weapon_17_0" since v7). Map JSON never holds
// a network sound id: SOUND_EMITTER and trigger "es" index config.emitterSounds (the v3.1.1 editor's
// sound picker lists emitterSounds, editor.js:76810, and only TRIGGER / SOUND_EMITTER have one),
// "esa" is a user asset id. v3.1.1's runtime read a (hand-written) BOT "es" as a network id
// (128.js triggerSound, unconverted); v7.1.4 and v10.0.3 read it as emitterSounds (addAI :187510), as
// KrunkNative does. So old maps load without a translation (shared/tests/network_sounds_test.c).
//
// A name the list lacks has no id: the bundle's indexOf answers -1 and the client plays
// networkSounds[-1], nothing (the melee pickup's "melee_equip", :176880; a spray sound past
// "spray_1"). The server paths that send by id resolve their name here first (spawnables.c,
// interact.c).
//
// "weapon_17_4" is listed twice (ids 135 and 155): indexOf answers 135, and 155 plays the same file.
// KrunkNative's own sound packets carry names, NET_SOUND_NAME_SIZE (64) bytes since protocol patch 7
// (shared.h NET_PROTOCOL_PATCH_SOUND_V2): every name here fits. A peer from before patch 7 reads 24-byte
// names, which "inspect_monte_carlo_spin" (24 characters) does not fit: the server does not send it that
// sound (net_sound_packet_to_v1), the one name such a peer misses.
