// Regenerates client/src/mod_shader_nodes.inc: the shader graph node catalogue of Krunker v10.0.7
// (deob-10.0.7.js:93193-94254: the value types, the graph limits, the node table and the per-kind output
// ports), evaluated from the decoded bundle and written as C data for client/src/mod_shader_graph.c.
// Only the schema is kept (ports, port types, defaults, param specs); labels and docs are not.
//   node tools/modshader/gen_nodes.cjs <game.deob.js> > client/src/mod_shader_nodes.inc
const fs = require('fs');
const lines = fs.readFileSync(process.argv[2], 'utf8').split('\n');
const start = lines.findIndex(l => /^  var \S+ = \['float', 'vec2', "vec3", "vec4"\];$/.test(l));
const end = lines.findIndex((l, i) => i > start && /^  var \S+ = new RegExp\(/.test(l));
if (start < 0 || end < 0) throw new Error('node table not found');
const src = lines.slice(start, end).join('\n');
const names = [...src.matchAll(/^  var (\S+) = /gm)].map(m => m[1]);
// the node table is the object whose first key is 'uv'; the kind table the one with 'surface'
const f = new Function(src + '\nreturn {' + names.map((n, i) => `v${i}: ${n}`).join(',') + '};');
const vars = Object.values(f());
const nodes = vars.find(v => v && v.uv && v.output && v.sceneColor);
const kinds = vars.find(v => v && v.surface && v.post);
const limits = vars.find(v => v && v.maxNodes);
const q = s => JSON.stringify(String(s));
const num = v => (Number.isFinite(v) ? String(v) : '0');
const out = [];
out.push(`// Generated by tools/modshader/gen_nodes.cjs from deob-10.0.7.js:${start + 1}-${end}: do not edit.`);
out.push(`#define MSG_MAX_NODES ${limits.maxNodes}`);
out.push(`#define MSG_MAX_PARAM_NODES ${limits.maxParamNodes}`);
out.push(`#define MSG_MAX_BYTES ${limits.maxBytes}`);
out.push(`#define MSG_MAX_ABS ${limits.maxAbsValue.toExponential()}`);
const T = {float: 'MSG_T_FLOAT', vec2: 'MSG_T_VEC2', vec3: 'MSG_T_VEC3', vec4: 'MSG_T_VEC4', any: 'MSG_T_ANY'};
const P = {number: 'MSG_P_NUMBER', vec2: 'MSG_P_VEC2', vec3: 'MSG_P_VEC3', vec4: 'MSG_P_VEC4', color: 'MSG_P_COLOR',
           enum: 'MSG_P_ENUM', string: 'MSG_P_STRING', value: 'MSG_P_VALUE', bool: 'MSG_P_BOOL'};
const port = (name, type, def) => {
  const d = def == null ? null : Array.isArray(def) ? def : [def];
  return `{${q(name)}, ${T[type]}, ${d ? d.length : 0}, {${d ? d.map(num).join(', ') : '0'}}}`;
};
const param = (name, p) => {
  const d = p.default;
  const dn = typeof d === 'number' ? [d] : Array.isArray(d) ? d : [];
  const ds = typeof d === 'string' ? q(d) : 'NULL';
  const en = p.enum ? `"${p.enum.join('|')}"` : 'NULL';
  return `{${q(name)}, ${P[p.type]}, ${p.optional ? 1 : 0}, ${d === null || d === undefined ? 1 : 0}, ${dn.length}, {${dn.length ? dn.map(num).join(', ') : '0'}}, ${ds}, ` +
         `${typeof d === 'boolean' ? (d ? 1 : 0) : 0}, ${en}, ${p.min != null ? 1 : 0}, ${num(p.min)}, ${p.max != null ? 1 : 0}, ${num(p.max)}, ${p.integer ? 1 : 0}}`;
};
out.push('static const MsgNodeDef MSG_NODES[] = {');
for (const [type, d] of Object.entries(nodes)) {
  const ins = Object.entries(d.inputs).map(([n, i]) => port(n, i.type, i.default));
  const outs = Object.entries(d.outputs).map(([n, t]) => port(n, t, null));
  const ps = Object.entries(d.params).map(([n, p]) => param(n, p));
  const postOnly = d.kinds ? (d.kinds.length === 1 && d.kinds[0] === 'post' ? 1 : 2) : 0;
  out.push(`    {${q(type)}, ${postOnly}, ${ins.length}, {${ins.join(', ') || '{0}'}}, ${outs.length}, {${outs.join(', ') || '{0}'}}, ` +
           `${ps.length}, {${ps.join(', ') || '{0}'}}},`);
}
out.push('};');
const post = kinds.post;
out.push(`// the post kind's output node: inputs ${JSON.stringify(post.inputs)}, params ${JSON.stringify(post.params)}`);
out.push(`static const char *const MSG_KINDS[] = {${Object.keys(kinds).map(q).join(', ')}};`);
console.log(out.join('\n'));
