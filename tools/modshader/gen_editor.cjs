// Regenerates client/src/ui/shader_graph_defs.inc: the node canvas editor's catalogue of Krunker v10.0.7, as JSON in
// a C string for client/src/ui/shader_graph_ui.c. It is v10's own data, evaluated from the decoded bundle:
//   - "defs": the editor's node definitions (iîìíiìï over the node table, deob-10.0.7.js:120821-121011): type,
//     title, category (iìíîíìî), description, inputs / outputs / params as the editor lists them (widget, default,
//     options, min, max, step, optional), kinds, and the output node's inputsByKind / paramsByKind;
//   - "templates": the Templates menu (iíìíiíì, :121012-122281), [id, graph] in v10's order.
//   node tools/modshader/gen_editor.cjs <game.deob.js> > client/src/ui/shader_graph_defs.inc
const fs = require('fs');
const lines = fs.readFileSync(process.argv[2], 'utf8').split('\n');

// the node table and the kind table (the region tools/modshader/gen_nodes.cjs evaluates)
const start = lines.findIndex(l => /^  var \S+ = \['float', 'vec2', "vec3", "vec4"\];$/.test(l));
const end = lines.findIndex((l, i) => i > start && /^  var \S+ = new RegExp\(/.test(l));
if (start < 0 || end < 0) throw new Error('node table not found');
const tsrc = lines.slice(start, end).join('\n');
const tnames = [...tsrc.matchAll(/^  var (\S+) = /gm)].map(m => m[1]);
const tvars = new Function(tsrc + '\nreturn {' + tnames.map(n => `${JSON.stringify(n)}: ${n}`).join(',') + '};')();
const nodesName = Object.keys(tvars).find(n => tvars[n] && tvars[n].uv && tvars[n].output && tvars[n].sceneColor);
const kindsName = Object.keys(tvars).find(n => tvars[n] && tvars[n].surface && tvars[n].post && !Array.isArray(tvars[n]));

// the editor's catalogue: from `var <kinds list> = ["surface", "paint", "post"];` to the templates' end
const ee = lines.findIndex((l, i) => i > end && /^  function \S+\(\S+\) \{$/.test(l) && lines[i + 1].includes('/[-_]+/g'));
const es = lines.findLastIndex((l, i) => i < ee && /^  var \S+ = \["surface", "paint", "post"\];$/.test(l));
if (es < 0 || ee < 0) throw new Error('editor catalogue not found');
const esrc = lines.slice(es, ee).join('\n');
const mapName = (esrc.match(/^  var (\S+) = new Map\(\);$/m) || [])[1];
const tplName = (esrc.match(/^  var (\S+) = \[\["animated-noise", \{$/m) || [])[1];
if (!mapName || !tplName) throw new Error('editor map / templates not found');
// the region's free names: the node / kind tables and Babel's helpers (createForOfIteratorHelper, slicedToArray, typeof)
const iterName = (esrc.match(/= (\S+)\(\S+\);\n  try \{/) || [])[1];
const sliceName = (esrc.match(/= (\S+)\(\S+\['value'\], 0x2\)/) || [])[1];
const helpers = `
  function ${iterName}(a) { let i = 0; const v = [...a]; return {s() {}, n() { return i < v.length ? {done: false, value: v[i++]} : {done: true}; }, e(x) { throw x; }, f() {}}; }
  function ${sliceName}(a) { return a; }`;
const typeofName = (esrc.match(/"object" === (\S+)\(/) || [])[1];
const body = helpers +
             (typeofName ? `\n  function ${typeofName}(x) { return typeof x; }` : '') + '\n' + esrc +
             `\nreturn {defs: [...${mapName}.values()], templates: ${tplName}};`;
const fnames = Object.keys(tvars).filter(n => esrc.includes(n));
const r = new Function(...fnames, body)(...fnames.map(n => tvars[n]));
const json = JSON.stringify({defs: r.defs, templates: r.templates});
const out = [];
out.push(`// Generated by tools/modshader/gen_editor.cjs from deob-10.0.7.js:${es + 1}-${ee} (with the node table, ` +
         `:${start + 1}-${end}): do not edit.`);
out.push(`// ${r.defs.length} node definitions, ${r.templates.length} templates; kinds table ${kindsName}.`);
out.push('static const char k_shader_graph_defs[] =');
for (let i = 0; i < json.length; i += 100) out.push('    ' + JSON.stringify(json.slice(i, i + 100)));
out.push('    ;');
console.log(out.join('\n'));
