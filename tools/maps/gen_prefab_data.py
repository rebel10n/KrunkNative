#!/usr/bin/env python3
"""Generates the shared Krunker v7.1.4 prefab / texture tables from the v7 sources.

    python3 -I tools/maps/gen_prefab_data.py

tools/maps/dump_v7.js loads the readable v7.1.4 data/prefabs.js (and config / triggers) under
node and prints them as JSON; this script writes

- shared/include/prefab_flags.h: PrefabFlag, one bit index per boolean property of the v7
  prefab table (the editor flags: editFaces, canInterface, noCol, ...), and
- shared/src/prefab_data.c: g_prefab_data[97] (name, src, model, default size, scale, line
  colour, opacity, edCat, texRange, variants, flag bits) and g_prefab_textures[20] (name,
  alias, src, variants).

The runtime semantics map.c needs (geometry, collision, which records make map objects) are
hand-written in shared/src/prefabs.c next to them. tools/editor/gen_editor_data.py builds the
editor's tables from the same dump.
"""

import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
V7_PUBLIC = "/home/user/jails/kru/src/Krunker_v7.1.4/public"

# properties of a prefab entry that are data, not boolean flags
NON_FLAGS = {"id", "name", "src", "defaultSize", "scale", "lineCol", "opacity", "edCat", "texRange",
             "variants", "gen", "CP", "CPY", "mlt", "alphaTest", "blending", "frameT", "frames", "width",
             "fakeScale"}


def dump_v7():
    out = subprocess.run(["node", os.path.join(HERE, "dump_v7.js")], check=True, capture_output=True,
                         text=True, cwd="/tmp").stdout
    return json.loads(out)


def c_str(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_float(v):
    r = repr(float(v))
    return r + "f" if ("." in r or "e" in r) else r + ".0f"


def flag_names(prefabs):
    names = set()
    for p in prefabs:
        for k, v in p.items():
            if k.startswith("has_") or k in NON_FLAGS:
                continue
            if isinstance(v, bool):
                names.add(k)
        if p.get("fakeScale"):
            names.add("fakeScale")
        for fn in ("gen", "genGeo", "editorGen"):
            if p.get("has_" + fn):
                names.add(fn)
    return sorted(names, key=lambda n: n.lower())


def model_of(prefab):
    m = re.search(r'"models/([a-z_0-9]+)\.obj"', prefab.get("gen") or "")
    return m.group(1) if m else None


def model_size(model, scale):
    """The bounds of models/<model>.obj at `scale` (ObjectInstance.promises defaultSize)."""
    for root in (os.path.join(REPO, "assets", "models"), os.path.join(V7_PUBLIC, "models")):
        path = os.path.join(root, model + ".obj")
        if not os.path.exists(path):
            continue
        lo, hi = [1e9] * 3, [-1e9] * 3
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("v "):
                    v = [float(x) for x in line.split()[1:4]]
                    lo = [min(a, b) for a, b in zip(lo, v)]
                    hi = [max(a, b) for a, b in zip(hi, v)]
        return [round((b - a) * scale, 3) for a, b in zip(lo, hi)]
    return None


def const_name(flag):
    return "PF_" + re.sub(r"[^A-Za-z0-9]", "", flag).upper()


def variants_c(name, variants):
    rows = []
    for v in variants:
        rows.append("    {%s, %d, %d, %d, %d}," % (c_str(v.get("name", "")), int(v.get("id", 0)),
                                                   1 if v.get("diffM") else 0, 1 if v.get("noEmis") else 0,
                                                   1 if v.get("complex") else 0))
    return "static const PrefabVariant %s[] = {\n%s\n};" % (name, "\n".join(rows))


def write_triggers(trig):
    """shared/src/trigger_v7_data.c: the v7 data/triggers.js tables (names, condition values, action
    UI flags) for the map validation, the editor and the WP-C runtime (shared/include/trigger_v7_data.h)."""
    lines = [
        "// GENERATED by tools/maps/gen_prefab_data.py from Krunker v7.1.4 data/triggers.js. Do not edit.",
        "#include <trigger_v7_data.h>",
        "",
        "const char *const g_trigger_v7_events[TRIGGER_V7_EVENT_COUNT] = {",
    ]
    lines += ["    %s," % c_str(e["name"]) for e in trig["events"]]
    lines += ["};", "", "const TriggerV7Condition g_trigger_v7_conditions[TRIGGER_V7_CONDITION_COUNT] = {"]
    for c in trig["conditions"]:
        vals = []
        for v in c["vals"]:
            kind = "TRIGGER_V7_VAL_NUMBER"
            if v.get("input"):
                kind = "TRIGGER_V7_VAL_INPUT"
            elif v.get("select") is not None:
                kind = "TRIGGER_V7_VAL_SELECT"
            elif v.get("bool"):
                kind = "TRIGGER_V7_VAL_BOOL"
            d = v.get("def")
            vals.append("{%s, %s, %s, %d, %d, %s, %s, %s}" % (
                c_str(v.get("name", "")), kind, c_float(d if isinstance(d, (int, float)) and not isinstance(d, bool) else 0),
                int(v.get("len") or 0), len(v.get("select") or []), c_float(v.get("min", 0)), c_float(v.get("max", 0)),
                c_float(v.get("step", 0))))
        lines.append("    {%s, %d, {%s}}," % (c_str(c["name"]), len(vals), ", ".join(vals) if vals else "{0}"))
    lines += ["};", "", "const TriggerV7Action g_trigger_v7_actions[TRIGGER_V7_ACTION_COUNT] = {"]
    for a in trig["actions"]:
        flags = []
        for key, flag in (("hasCust", "TRIGGER_V7_ACT_CUST"), ("hasSound", "TRIGGER_V7_ACT_SOUND"),
                          ("hasExtra", "TRIGGER_V7_ACT_EXTRA"), ("devOnly", "TRIGGER_V7_ACT_DEV_ONLY"),
                          ("bypassType", "TRIGGER_V7_ACT_BYPASS_TYPE")):
            if a.get(key):
                flags.append(flag)
        if a.get("type") == "Text":
            flags.append("TRIGGER_V7_ACT_TEXT")
        elif a.get("type") == "Both":
            flags.append("TRIGGER_V7_ACT_BOTH")
        lines.append("    {%s, %s, %s, %s, %s, %d, %d}," % (
            c_str(a["name"]), " | ".join(flags) if flags else "0", c_str(a.get("actionValue")),
            c_str(a.get("actionValue2")), c_str(a.get("actionValueTxt")), len(a.get("actionOptions") or []),
            len(a.get("actionOptions2") or [])))
    lines += ["};", ""]
    with open(os.path.join(REPO, "shared", "src", "trigger_v7_data.c"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    if (len(trig["events"]), len(trig["conditions"]), len(trig["actions"])) != (32, 12, 72):
        print("warning: trigger table sizes changed: %d / %d / %d" % (
            len(trig["events"]), len(trig["conditions"]), len(trig["actions"])))


def main():
    data = dump_v7()
    prefabs, textures = data["prefabs"], data["textures"]
    flags = flag_names(prefabs)
    if len(flags) > 128:
        raise SystemExit("more than 128 prefab flags")

    header = [
        "// GENERATED by tools/maps/gen_prefab_data.py from Krunker v7.1.4 data/prefabs.js. Do not edit.",
        "// Bit indices of the boolean prefab properties (prefab_has_flag, shared/include/prefabs.h).",
        "#pragma once",
        "",
        "typedef enum {",
    ]
    for i, f in enumerate(flags):
        header.append("    %s = %d, // %s" % (const_name(f), i, f))
    header += ["    PF_FLAG_COUNT = %d" % len(flags), "} PrefabFlag;", ""]
    with open(os.path.join(REPO, "shared", "include", "prefab_flags.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(header))

    lines = [
        "// GENERATED by tools/maps/gen_prefab_data.py from Krunker v7.1.4 data/prefabs.js. Do not edit.",
        "#include <prefabs.h>",
        "",
    ]
    for p in prefabs:
        if p.get("variants"):
            lines.append(variants_c("k_prefab_variants_%d" % p["id"], p["variants"]))
    for i, t in enumerate(textures):
        if t.get("variants"):
            lines.append(variants_c("k_texture_variants_%d" % i, t["variants"]))
    lines += ["", "const PrefabData g_prefab_data[PREFAB_TABLE_COUNT] = {"]
    for p in prefabs:
        bits = [0, 0]
        for i, f in enumerate(flags):
            on = p.get(f) is True or (f in ("gen", "genGeo", "editorGen") and p.get("has_" + f)) or \
                 (f == "fakeScale" and p.get("fakeScale"))
            if on:
                bits[i // 64] |= 1 << (i % 64)
        model = model_of(p)
        size = p.get("defaultSize")
        has_size = 1 if size else 0
        if not size and model:
            size = model_size(model, p.get("scale") or 1)
            has_size = 2 if size else 0
        src = p.get("src") if isinstance(p.get("src"), str) else None
        nvar = len(p.get("variants") or [])
        lines.append("    [%d] = {%s, %s, %s, {%s}, %d, %s, %d, %s, %s, %d, %d, %s, {0x%016xull, 0x%016xull}}," % (
            p["id"], c_str(p["name"]), c_str(src), c_str(model),
            ", ".join(c_float(v) for v in (size or [1, 1, 1])), has_size,
            c_float(p.get("scale") or 1), p["lineCol"] if p.get("lineCol") is not None else -1,
            c_float(p["opacity"] if p.get("opacity") is not None else 1), c_str(p.get("edCat")),
            int(p.get("texRange") or 0), nvar, ("k_prefab_variants_%d" % p["id"]) if nvar else "NULL",
            bits[0], bits[1]))
    lines += ["};", "", "const PrefabTextureData g_prefab_textures[PREFAB_TEXTURE_COUNT] = {"]
    for i, t in enumerate(textures):
        nvar = len(t.get("variants") or [])
        lines.append("    [%d] = {%s, %s, %s, %d, %s}," % (i, c_str(t["name"]), c_str(t.get("alias")), c_str(t.get("src")),
                                                        nvar, ("k_texture_variants_%d" % i) if nvar else "NULL"))
    lines += ["};", "", "const char *const g_prefab_flag_names[PF_FLAG_COUNT] = {"]
    lines += ["    %s," % c_str(f) for f in flags]
    lines += ["};", ""]
    with open(os.path.join(REPO, "shared", "src", "prefab_data.c"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    write_triggers(data["triggers"])
    if len(prefabs) != 97 or len(textures) != 20:
        print("warning: %d prefabs, %d textures (prefabs.h expects 97 / 20)" % (len(prefabs), len(textures)))
    print("wrote shared/src/prefab_data.c (%d prefabs, %d textures, %d flags)" % (len(prefabs), len(textures), len(flags)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
