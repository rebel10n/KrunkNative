"""Generates client/src/ui/economy_black_market_table.c from assets/skins.json: the Black Market items.

v10's Black Market tab lists every store item with ``blackM`` that is neither ``free`` nor ``hide``
(deob-10.0.7.js:137663-137676) and checks each one's requirement with store.checkReq
(deob-10.0.7.js:103566-103580): ``accAge`` / ``stats`` / ``accVar`` / ``rank`` / ``ownSkins``; anything
else (``disabled``) is never met, an item with no ``req`` always is. The viewer store table
(viewer_store_table.c) carries none of these fields, so the client keeps this table beside it.
The table keeps the hidden / free items too (``hide`` / ``free_``): the Catalog's Black Market category and
the item badge name every blackM item.

  python3 -I tools/ui-import/gen_black_market.py [--check] [assets/skins.json] [out.c]

--check: exit 1 when the C file is not what the table gives (make store-check).
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
KINDS = {"accAge": "ECON_REQ_ACC_AGE", "stats": "ECON_REQ_STATS", "accVar": "ECON_REQ_ACC_VAR",
         "rank": "ECON_REQ_RANK", "ownSkins": "ECON_REQ_OWN_SKINS"}


def cstr(s):
    if s is None:
        return "NULL"
    out = []
    for b in str(s).encode("utf-8"):
        c = chr(b)
        if c in "\\\"":
            out.append("\\" + c)
        elif 0x20 <= b < 0x7f:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def num(v):
    """v10's table has some amounts as strings ("1000"); checkReq compares them as numbers"""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return 0.0
    return f


def truthy(v):
    return bool(v) and v != "false"


def generate(skins):
    rows, lists = [], []
    for index, s in enumerate(skins):
        if not isinstance(s, dict) or not truthy(s.get("blackM")):
            continue
        req = s.get("req")
        kind = "ECON_REQ_NONE" if not req else KINDS.get(req, "ECON_REQ_NEVER")
        skins_ref, n_skins = "NULL", 0
        if kind == "ECON_REQ_OWN_SKINS":
            ids = [int(x) for x in (s.get("reqSkins") or [])]
            lists.append("static const int k_req_%d[] = {%s};" % (index, ", ".join(str(i) for i in ids)))
            skins_ref, n_skins = "k_req_%d" % index, len(ids)
        amount = num(s.get("reqAmount"))
        rows.append("    {.skin = %d, .funds = %d, .req_t = %s, .req = %s, .var = %s, .amount = %s, .skins = %s, .skin_count = %d, "
                    ".hide = %d, .free_ = %d},"
                    % (index, int(num(s.get("funds"))), cstr(s.get("reqT")), kind,
                       cstr(s.get("reqVar")) if kind in ("ECON_REQ_STATS", "ECON_REQ_ACC_VAR") else "NULL",
                       repr(amount) if amount != int(amount) else "%d.0" % int(amount), skins_ref, n_skins,
                       1 if truthy(s.get("hide")) else 0, 1 if truthy(s.get("free")) else 0))
    text = ("// Generated by tools/ui-import/gen_black_market.py from assets/skins.json (the v10 store table): every\n"
            "// blackM item with its price, requirement (store.checkReq, deob-10.0.7.js:103566-103580) and hide / free.\n"
            "// Do not edit: re-run the generator (make store-import).\n"
            "#include <economy_client.h>\n\n")
    if lists:
        text += "\n".join(lists) + "\n\n"
    text += "const EconBlackMarketItem g_econ_black_market[] = {\n" + "\n".join(rows) + "\n};\n"
    text += "const int g_econ_black_market_count = %d;\n" % len(rows)
    return text, len(rows)


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    src = args[0] if args else os.path.join(REPO, "assets", "skins.json")
    out = args[1] if len(args) > 1 else os.path.join(REPO, "client", "src", "ui", "economy_black_market_table.c")
    with open(src, encoding="utf-8") as fh:
        skins = json.load(fh)
    text, n = generate(skins)
    rel = os.path.relpath(out, REPO)
    if check:
        cur = open(out, encoding="utf-8").read() if os.path.isfile(out) else ""
        if cur != text:
            print("[gen_black_market] %s is out of date" % rel)
            return 1
        print("[gen_black_market] %s up to date (%d items)" % (rel, n))
        return 0
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("[gen_black_market] wrote %s (%d items)" % (rel, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
