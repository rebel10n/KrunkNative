#!/usr/bin/env python3
"""Generate client/src/cosmetics_table.c from assets/skins.json (the store table).

The table holds the store skins that dress the player model (client/include/cosmetics.h):
hats (1), bodies (2), dyes (5), waists (6), faces (7) and v7's HEAD (15) / BACK (14) items,
which load their meshes from hats/ and body/ (v7 src/data/store.js assetType) and are worn in
the hat / back slots. Only the fields the player model reads are kept; cosmetics.c and
player_mesh.c apply them. v7 skins with ``hasAnim`` load ``<model>.<fileExt || gltf>``
through client/src/gltf.c (v7 src/libs/render.js loadAnimMesh).

usage: python3 -I tools/ui-import/gen_cosmetics.py [--skins assets/skins.json] [--out client/src/cosmetics_table.c] [--check]
"""

import argparse
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TYPES = (1, 2, 5, 6, 7, 14, 15)
ASSET_TYPE = {14: 2, 15: 1}  # v7 store.js: BACK -> body/body_, HEAD -> hats/hat_


def num(v):
    """A JS number as a C float literal (shortest round-trip repr, like the JS source)."""
    r = repr(float(v))
    if "e" in r or "E" in r:
        r = "%.9g" % float(v)
        if "." not in r and "e" not in r:
            r += ".0"
    return r + "f"


def colour(v):
    """A dye colour: number, "#rrggbb" or (v7) an array the client picks from at random; the
    first entry here. -1 = keep the class colour."""
    if isinstance(v, list):
        v = v[0] if v else None
    if isinstance(v, str) and v.startswith("#"):
        v = int(v[1:], 16)
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return "-1"
    return "0x%06X" % int(v)


def c_string(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ord(ch) < 0x20:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def entry(index, s):
    t = s.get("type", 0)
    tex = s.get("tex")
    fields = [
        ".index = %d" % index,
        ".type = %d" % t,
        ".id = %d" % int(s.get("id") or 0),
        ".name = %s" % c_string(s.get("name", "")),
        ".tex = %d" % (int(tex) if isinstance(tex, (int, float)) and not isinstance(tex, bool) else -1),
        ".scl_mlt = %s" % num(s.get("sclMlt") or 1),
        ".sit_off = %s" % num(s.get("sitOff") or 0),
        ".sit_off_z = %s" % num(s.get("sitOffZ") or 0),
        ".opacity = %s" % num(s.get("opac") or 1),
        ".alpha_test = %s" % num(s.get("alpha") or 0),
        ".double_sided = %d" % (1 if s.get("side") == 2 else 0),
        ".color = %s" % colour(s.get("color")),
        ".skin_col = %s" % colour(s.get("skinCol")),
        ".shirt_col = %s" % colour(s.get("shirtCol")),
        ".sleeve_col = %s" % colour(s.get("sleeveCol")),
        ".pants_col = %s" % colour(s.get("pantsCol")),
        ".shoe_col = %s" % colour(s.get("shoeCol")),
        ".hair_col = %s" % colour(s.get("hairCol")),
    ]
    if t in ASSET_TYPE:
        fields.append(".asset_type = %d" % ASSET_TYPE[t])
    if s.get("hasAnim"):
        fields.append(".anim_s = %s" % num(s.get("animS") or 1))
        fields.append('.file_ext = "%s"' % (s.get("fileExt") or "gltf"))
    for key, flag in (("noHead", "no_head"), ("noLegs", "no_legs")):
        if s.get(key):
            fields.append(".%s = 1" % flag)
    if s.get("opac") is not None or s.get("trans"):
        fields.append(".transparent = 1")
    if s.get("hasAnim"):
        fields.append(".has_anim = 1")
    return "    {" + ", ".join(fields) + "},"


def generate(skins):
    lines = [
        "// Generated by tools/ui-import/gen_cosmetics.py from assets/skins.json (Krunker v7.1.4 store.skins):",
        "// skins of type 1 hat, 2 body, 5 dye, 6 waist, 7 face, 14 back and 15 head, sorted by store index.",
        "// Only the fields the player model uses are kept; see cosmetics.c for how they are applied.",
        "#include <cosmetics.h>",
        "",
        "const Cosmetic g_cosmetics[] = {",
    ]
    for i, s in enumerate(skins):
        if s.get("type", 0) in TYPES:
            lines.append(entry(i, s))
    lines += [
        "};",
        "",
        "const size_t g_cosmetic_count = sizeof(g_cosmetics) / sizeof(g_cosmetics[0]);",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--skins", default=os.path.join(REPO, "assets", "skins.json"))
    ap.add_argument("--out", default=os.path.join(REPO, "client", "src", "cosmetics_table.c"))
    ap.add_argument("--check", action="store_true", help="exit 1 when --out is not up to date")
    args = ap.parse_args()

    with open(args.skins, encoding="utf-8") as fh:
        skins = json.load(fh)
    text = generate(skins)
    try:
        with open(args.out, encoding="utf-8") as fh:
            current = fh.read()
    except OSError:
        current = None
    count = text.count("\n    {")
    if current == text:
        print("cosmetics table: %d items, up to date" % count)
        return
    if args.check:
        print("cosmetics table: %s is out of date" % args.out)
        sys.exit(1)
    with open(args.out + ".tmp", "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(args.out + ".tmp", args.out)
    print("cosmetics table: %d items written to %s" % (count, args.out))


if __name__ == "__main__":
    main()
