#!/usr/bin/env python3 -I
"""Generate the Material Icons ligature table for the native HTML engine.

Reads a Material Icons font (WOFF2 or TTF), walks every GSUB ligature
substitution (the font ships them under the `rlig` feature, lookup type 4),
maps each ligature's component glyphs back to text through the cmap and emits:

  * a C header `name -> Unicode codepoint (PUA)` table sorted by name, and
  * optionally the same font converted to plain TTF (no brotli at runtime).

Usage:
  python3 -I tools/ui-import/gen_liga.py \
      --font ui/css/fonts/flUhRq6tzZclQEJ-Vdg-IuiaDsNc.woff2 \
      --header client/src/html/engine/material_icons_liga.h \
      --ttf ui/css/fonts/material-icons.ttf

Dependencies: fonttools (+ brotli for WOFF2 input).  The script is meant to be
run with `python3 -I` (no cwd/script-dir imports); because -I also drops the
per-user site-packages directory where `pip install --user` puts fonttools, that
directory is appended explicitly below (it is a trusted install location, not
the untrusted input directory).
"""
import argparse
import os
import site
import sys

try:
    from fontTools.ttLib import TTFont
except ModuleNotFoundError:
    sys.path.append(site.getusersitepackages())
    for p in sys.path[:]:
        if "/usr/lib" in p and "site-packages" in p:
            sys.path.append(p.replace("/usr/lib", "/usr/local/lib", 1))
    try:
        from fontTools.ttLib import TTFont
    except ModuleNotFoundError:
        sys.exit("fonttools not found: pip install --user fonttools brotli")


def reverse_cmap(font):
    rev = {}
    for cp, name in font.getBestCmap().items():
        # Prefer the lowest codepoint per glyph (ASCII letters before fullwidth
        # duplicates); PUA ligature glyphs normally have exactly one.
        if name not in rev or cp < rev[name]:
            rev[name] = cp
    return rev


def collect_ligatures(font):
    rev = reverse_cmap(font)
    order = font.getGlyphOrder()
    ligs = {}
    if "GSUB" not in font:
        return ligs
    gsub = font["GSUB"].table
    for lookup in gsub.LookupList.Lookup:
        subtables = []
        for st in lookup.SubTable:
            if lookup.LookupType == 7:  # extension
                st = st.ExtSubTable
            if getattr(st, "ligatures", None) is not None:
                subtables.append(st)
        for st in subtables:
            for first, entries in st.ligatures.items():
                for lig in entries:
                    comps = [first] + list(lig.Component)
                    try:
                        name = "".join(chr(rev[g]) for g in comps)
                    except KeyError:
                        continue  # component glyph without a codepoint
                    cp = rev.get(lig.LigGlyph, 0)
                    gid = order.index(lig.LigGlyph)
                    if name not in ligs or (cp and not ligs[name][0]):
                        ligs[name] = (cp, gid)
    return ligs


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_header(path, ligs, font_name):
    names = sorted(ligs)  # strcmp order: plain byte order of ASCII names
    with open(path, "w") as out:
        out.write("/* GENERATED by tools/ui-import/gen_liga.py from %s. DO NOT EDIT. */\n" % font_name)
        out.write("#pragma once\n#include <stdint.h>\n\n")
        out.write("/* Material Icons ligature names -> PUA codepoint (0 if the ligature glyph is\n"
                  " * unmapped; use glyph_index then).  Sorted by name (strcmp order). */\n")
        out.write("typedef struct MaterialIconLiga {\n    const char *name;\n    uint32_t codepoint;\n    uint32_t glyph_index;\n} MaterialIconLiga;\n\n")
        out.write("#define MATERIAL_ICONS_LIGA_COUNT %d\n" % len(names))
        out.write("#define MATERIAL_ICONS_LIGA_MAX_NAME %d\n\n" % max(len(n) for n in names))
        out.write("static const MaterialIconLiga material_icons_liga[MATERIAL_ICONS_LIGA_COUNT] = {\n")
        for n in names:
            cp, gid = ligs[n]
            out.write('    {"%s", 0x%04x, %d},\n' % (c_escape(n), cp, gid))
        out.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True)
    ap.add_argument("--header", required=True)
    ap.add_argument("--ttf", help="also save the font as plain TTF here")
    args = ap.parse_args()

    font = TTFont(args.font)
    ligs = collect_ligatures(font)
    if not ligs:
        sys.exit("no ligatures found in %s" % args.font)
    write_header(args.header, ligs, os.path.basename(args.font))
    unmapped = sum(1 for cp, _ in ligs.values() if not cp)
    print("%d ligatures (%d without a codepoint) -> %s" % (len(ligs), unmapped, args.header))
    if args.ttf:
        font.flavor = None
        font.save(args.ttf)
        print("saved %s (%d glyphs)" % (args.ttf, len(font.getGlyphOrder())))


if __name__ == "__main__":
    main()
