#!/usr/bin/env node
// Writes assets/shaders/shadertoy/<id>.glsl: the mainImage() code of Krunker v7.1.4's skin shaders
// (src/data/shaders.js, skin `shaderNum` 0-7), verbatim. client/src/skin_fx.c wraps each in the
// ShaderToyMaterial prelude (v7 src/133.js C240: iResolution, iTime, iChannel0, ...).
//   node tools/ui-import/gen_shadertoy.js [Krunker_v7.1.4 root]      GEN_CHECK=1: drift check only
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const REPO = path.resolve(__dirname, '..', '..');
const ROOT = process.argv[2] || '/home/user/jails/kru/src/Krunker_v7.1.4';
const OUT = path.join(REPO, 'assets/shaders/shadertoy');

const mod = { exports: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'src/data/shaders.js'), 'utf8'), { module: mod, exports: mod.exports, Math });
const shaders = mod.exports;
let drift = 0;
for (const s of shaders) {
  const text = `// Krunker v7.1.4 src/data/shaders.js #${s.id} "${s.name}" (generated by tools/ui-import/gen_shadertoy.js)\n` + s.code.replace(/^\n/, '') + '\n';
  const file = path.join(OUT, `${s.id}.glsl`);
  if (process.env.GEN_CHECK) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.log('[gen_shadertoy] ' + path.relative(REPO, file) + ' is out of date'); drift++; }
  } else {
    fs.mkdirSync(OUT, { recursive: true });
    fs.writeFileSync(file, text);
  }
}
console.log(`[gen_shadertoy] ${shaders.length} shaders ${process.env.GEN_CHECK ? (drift ? 'OUT OF DATE' : 'up to date') : 'written'}`);
process.exit(drift ? 1 : 0);
