#!/usr/bin/env python3
"""Generated stopgaps for FRVR's Strike stylesheet (ui/strike/css/kn-strike-overrides.css).

    python3 -I tools/strike/strike_overrides.py [--css ui/strike/assets/index-CJ_IUjn5.css]
                                               [--out ui/strike/css/kn-strike-overrides.css]

FRVR's assets/index-CJ_IUjn5.css is shipped unchanged. Where the native HTML engine
(client/src/html/engine/, owned by the E1-E3 agents) lacks a feature the stylesheet relies on,
this script writes an equivalent rule (same selector, loaded after FRVR's sheet) between the
GENERATED markers of kn-strike-overrides.css; the hand-written stopgaps above the markers stay.
Each stopgap goes away when the engine gains the feature:

  GAP translate / scale (CSS Transforms 2 individual properties): `translate: X Y` / `scale: S`
      -> `transform: translate(X, Y) scale(S) <the rule's own transform>`.
  GAP clip-path polygon(): at most CSS_MAX_CLIP_POINTS = 8 points, filled by ear clipping (one
      simple ring). FRVR's bevelled shapes use up to 20 points, and its frames are two rings in
      one polygon (the outer outline, then back to the first point and around the inner one: the
      nonzero rule leaves a hole, a 1-4 unit border). Stopgap:
        - one ring with more than 8 points: the 8 that keep the most area (Visvalingam-Whyatt on a
          200 x 60 base-unit reference box; the dropped ones are the smallest bevel steps);
        - a frame: the outer ring (simplified the same way) as the clip and the inner ring's
          insets per side as a solid border in the rule's background colour (the bevel diagonals
          lose their stroke, the silhouette and the straight edges match).
The browser never sees a difference that matters: it supports all of the above, and these rules
re-state what it computes (translate/scale) or are drawn by the same pixels (clip-path).
Never executes anything it reads; run it with python3 -I.
"""
import argparse, ast, math, os, re, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BEGIN = '/* ==== GENERATED by tools/strike/strike_overrides.py: do not edit below ==== */'
END = '/* ==== END GENERATED ==== */'
MAX_POINTS = 8          # client/src/html/engine/css_types.h CSS_MAX_CLIP_POINTS
REF_W, REF_H = 200.0, 60.0


def top_rules(css):
    """(selector, body) of the top-level style rules (no @media / @keyframes / @font-face content)"""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip()
        d, k = 1, j + 1
        while k < n and d:
            if css[k] == '{': d += 1
            elif css[k] == '}': d -= 1
            k += 1
        body = css[j + 1:k - 1]
        if not sel.startswith('@') and '{' not in body: out.append((sel, body))
        i = k
    return out


def split_top(s, sep=','):
    depth, cur, out = 0, '', []
    for ch in s:
        if ch == '(': depth += 1
        elif ch == ')': depth -= 1
        if ch == sep and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out


def decls(body):
    """[(prop, value)] in order"""
    out = []
    for d in split_top(body, ';'):
        if ':' not in d: continue
        p, v = d.split(':', 1)
        out.append((p.strip().lower(), v.strip()))
    return out


def find_func(value, name):
    """the argument text of name(...) in value, else None"""
    i = value.find(name + '(')
    if i < 0: return None
    k, d = i + len(name) + 1, 1
    e = k
    while e < len(value) and d:
        if value[e] == '(': d += 1
        elif value[e] == ')': d -= 1
        e += 1
    return value[k:e - 1]


# ---------------------------------------------------------------- lengths

def evaluate(expr, extent):
    """a clip-path coordinate in base units on the reference box (extent = its width / height)"""
    s = expr.strip()
    if s.startswith('calc(') and s.endswith(')'): s = s[5:-1]
    s = re.sub(r'var\(--(?:base-scale|one-pixel-scaled)\)', '(1)', s)
    s = re.sub(r'(-?[\d.]+)%', lambda m: '(%s*%r/100)' % (m.group(1), extent), s)
    s = re.sub(r'(-?[\d.]+)px', lambda m: '(%s/2)' % m.group(1), s)
    if re.search(r'[a-zA-Z]', s): raise ValueError(expr)
    node = ast.parse(s, mode='eval')
    for n in ast.walk(node):
        if not isinstance(n, (ast.Expression, ast.BinOp, ast.UnaryOp, ast.Constant, ast.Add, ast.Sub, ast.Mult, ast.Div,
                              ast.USub, ast.UAdd)):
            raise ValueError(expr)
    return float(eval(compile(node, '<len>', 'eval'), {'__builtins__': {}}, {}))


def affine(expr):
    """expr as (percent factor 0..1, base units): x = a * extent + b"""
    v0 = evaluate(expr, 0.0)
    v1 = evaluate(expr, 1000.0)
    return (v1 - v0) / 1000.0, v0


# ---------------------------------------------------------------- polygons

def points(poly_args):
    pts = []
    for p in split_top(poly_args):
        xy = split_top(p, ' ')
        if len(xy) != 2: raise ValueError(p)
        pts.append((xy[0], xy[1]))
    return pts


def rings(pts):
    """the polygon's rings: a later repeat of the first point closes the outer one"""
    first = pts[0]
    for i in range(1, len(pts)):
        if pts[i] == first: return [pts[:i], pts[i + 1:] if pts[i + 1:] and pts[-1] == pts[i + 1] else pts[i + 1:]]
    return [pts]


def simplify(ring, keep=MAX_POINTS):
    """Visvalingam-Whyatt down to `keep` points on the reference box"""
    xy = [(evaluate(x, REF_W), evaluate(y, REF_H)) for x, y in ring]
    idx = list(range(len(ring)))
    def area(k):
        a, b, c = xy[idx[k - 1]], xy[idx[k]], xy[idx[(k + 1) % len(idx)]]
        return abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1])) / 2
    while len(idx) > keep:
        k = min(range(len(idx)), key=area)
        del idx[k]
    return [ring[i] for i in idx]


def insets(inner):
    """per-side border widths (base units) from the inner ring: top right bottom left"""
    side = {'top': [], 'right': [], 'bottom': [], 'left': []}
    for x, y in inner:
        ax, bx = affine(x)
        ay, by = affine(y)
        if abs(ax) < 1e-6: side['left'].append(bx)
        elif abs(ax - 1) < 1e-6: side['right'].append(-bx)
        if abs(ay) < 1e-6: side['top'].append(by)
        elif abs(ay - 1) < 1e-6: side['bottom'].append(-by)
    out = []
    for s in ('top', 'right', 'bottom', 'left'):
        v = [w for w in side[s] if w >= 0]
        out.append(min(v) if v else 0.0)
    return out


def color_of(rule_decls):
    for p, v in rule_decls:
        if p in ('background', 'background-color'):
            v = v.replace('!important', '').strip()
            if re.fullmatch(r'#[0-9a-fA-F]{3,8}|rgba?\([^()]*\)|[a-z]+|var\(--[\w-]+\)', v): return v
    return None


def compound_key(selector):
    """(classes of the last compound, its pseudo-element) or None"""
    last = re.split(r'[\s>+~]+', selector.strip())[-1]
    m = re.search(r'::?(before|after)$', last)
    if not m: return None
    return (frozenset(re.findall(r'\.([\w-]+)', last)), m.group(1))


def fmt_len(units):
    return '0' if abs(units) < 1e-9 else 'calc(%g * var(--base-scale))' % round(units, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--css', default=os.path.join(REPO, 'ui', 'strike', 'assets', 'index-CJ_IUjn5.css'))
    ap.add_argument('--out', default=os.path.join(REPO, 'ui', 'strike', 'css', 'kn-strike-overrides.css'))
    a = ap.parse_args()
    css = open(a.css, encoding='utf-8').read()
    out, stats, frames = [], {'translate': 0, 'simplified': 0, 'frames': 0, 'skipped': 0}, []
    for sel, body in top_rules(css):
        ds = decls(body)
        props = dict(ds)
        extra = []
        # individual transform properties
        tr, sc = props.get('translate'), props.get('scale')
        if (tr or sc) and tr not in ('none',) and sc not in ('none',):
            parts = []
            if tr:
                tv = split_top(tr, ' ')
                parts.append('translate(%s)' % ', '.join(tv) if len(tv) > 1 else 'translate(%s)' % tv[0])
            if sc:
                parts.append('scale(%s)' % ', '.join(split_top(sc, ' ')))
            own = props.get('transform')
            if own and own != 'none': parts.append(own)
            extra.append('transform:%s' % ' '.join(parts))
            stats['translate'] += 1
        # clip-path polygons the engine cannot take
        cp = props.get('clip-path') or props.get('-webkit-clip-path')
        args = find_func(cp, 'polygon') if cp else None
        if args:
            try:
                pts = points(args)
                if len(pts) > MAX_POINTS:
                    rs = rings(pts)
                    outer = simplify(rs[0]) if len(rs[0]) > MAX_POINTS else rs[0]
                    poly = 'polygon(%s)' % ','.join('%s %s' % p for p in outer)
                    if len(rs) > 1 and rs[1]:
                        col = color_of(ds)
                        if col:
                            t, r, b, l = insets(rs[1])
                            extra.append('clip-path:%s;border-style:solid;border-color:%s;border-width:%s %s %s %s;background:transparent;box-sizing:border-box'
                                         % (poly, col, fmt_len(t), fmt_len(r), fmt_len(b), fmt_len(l)))
                            stats['frames'] += 1
                        else:
                            extra.append('clip-path:%s' % poly)
                            stats['skipped'] += 1
                    else:
                        extra.append('clip-path:%s' % poly)
                        stats['simplified'] += 1
            except (ValueError, SyntaxError, ZeroDivisionError) as e:
                stats['skipped'] += 1
                print('skip %s: %s' % (sel[:60], e), file=sys.stderr)
        if extra: out.append('%s{%s}' % (sel, ';'.join(extra)))
        if any(e.startswith('clip-path:') and 'border-style' in e for e in extra):
            frames.extend(compound_key(x) for x in split_top(sel))
    # the frames' colour variants (.frvr-button.frvr-button--green:after{background:...}): their
    # background becomes the border colour, the inside stays transparent
    recolored = 0
    for sel, body in top_rules(css):
        col = color_of(decls(body))
        if not col: continue
        hits = [x for x in split_top(sel) if any(k and compound_key(x) and k[1] == compound_key(x)[1] and k[0] <= compound_key(x)[0] for k in frames)]
        if hits and not any(compound_key(x) in frames and x == sel for x in hits):
            out.append('%s{border-color:%s;background:transparent}' % (','.join(hits), col))
            recolored += 1
    stats['recolored'] = recolored
    text = open(a.out, encoding='utf-8').read() if os.path.exists(a.out) else ''
    head = text.split(BEGIN)[0].rstrip() + '\n\n' if BEGIN in text else text.rstrip() + '\n\n'
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(head + BEGIN + '\n' + '\n'.join(out) + '\n' + END + '\n')
    print('%(translate)d transform, %(simplified)d simplified polygons, %(frames)d frames (%(recolored)d colour variants), %(skipped)d skipped' % stats)


if __name__ == '__main__':
    main()
