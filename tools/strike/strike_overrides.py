#!/usr/bin/env python3
"""Generated stopgaps for FRVR's Strike stylesheet (ui/strike/css/kn-strike-overrides.css).

    python3 -I tools/strike/strike_overrides.py [--css ui/strike/assets/index-CJ_IUjn5.css]
                                               [--out ui/strike/css/kn-strike-overrides.css]

FRVR's assets/index-CJ_IUjn5.css is shipped unchanged. Where the native HTML engine
(client/src/html/engine/) lacks a feature the stylesheet relies on, this script writes an
equivalent rule (same selector, loaded after FRVR's sheet) between the GENERATED markers of
kn-strike-overrides.css; the hand-written stopgaps above the markers stay. Each stopgap goes away
when the engine gains the feature:

  GAP translate / scale (CSS Transforms 2 individual properties): `translate: X Y` / `scale: S`
      -> `transform: translate(X, Y) scale(S) <the rule's own transform>`, in style rules and in
      @keyframes (shine-slide: the buttons' and the selected class bullet's shine; fade-in; FRVR's
      animated elements have no transform of their own, so the frames' transform is the whole of it).

A stopgap sits after all of FRVR's sheet, so it would also beat FRVR's later rules of the same
specificity. Each later rule that sets `transform` is therefore re-stated after it, in FRVR's order,
with only that declaration: the cascade between FRVR's own rules comes out as FRVR wrote it.
(clip-path polygons, frames of two rings included, are the engine's own since strike-pixel-2.)
The browser never sees a difference that matters: it supports all of the above, and these rules
re-state what it computes. Never executes anything it reads; run it with python3 -I.
"""
import argparse, os, re, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BEGIN = '/* ==== GENERATED by tools/strike/strike_overrides.py: do not edit below ==== */'
END = '/* ==== END GENERATED ==== */'


def keyframes_blocks(css):
    """(name, [(selector, body)]) of the top-level @keyframes (not -webkit-) blocks"""
    out = []
    for m in re.finditer(r'@keyframes\s+([\w-]+)\s*\{', css):
        d, k = 1, m.end()
        while k < len(css) and d:
            if css[k] == '{': d += 1
            elif css[k] == '}': d -= 1
            k += 1
        out.append((m.group(1), top_rules(css[m.end():k - 1])))
    return out


def transform_of(props):
    """the transform for the rule's translate / scale (and own transform), else None"""
    tr, sc = props.get('translate'), props.get('scale')
    if not (tr or sc) or tr == 'none' or sc == 'none': return None
    parts = []
    if tr:
        tv = split_top(tr, ' ')
        parts.append('translate(%s)' % ', '.join(tv) if len(tv) > 1 else 'translate(%s)' % tv[0])
    if sc:
        parts.append('scale(%s)' % ', '.join(split_top(sc, ' ')))
    own = props.get('transform')
    if own and own != 'none': parts.append(own)
    return ' '.join(parts)


def top_rules(css):
    """(selector, body) of the top-level style rules (no @media / @keyframes / @font-face content)"""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip()
        d, k = 1, j + 1
        while k < n and d:
            if css[k] == '{': d += 1
            elif css[k] == '}': d -= 1
            k += 1
        body = css[j + 1:k - 1]
        if not sel.startswith('@') and '{' not in body: out.append((sel, body))
        i = k
    return out


def split_top(s, sep=','):
    depth, cur, out = 0, '', []
    for ch in s:
        if ch == '(': depth += 1
        elif ch == ')': depth -= 1
        if ch == sep and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out


def decls(body):
    """[(prop, value)] in order"""
    out = []
    for d in split_top(body, ';'):
        if ':' not in d: continue
        p, v = d.split(':', 1)
        out.append((p.strip().lower(), v.strip()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--css', default=os.path.join(REPO, 'ui', 'strike', 'assets', 'index-CJ_IUjn5.css'))
    ap.add_argument('--out', default=os.path.join(REPO, 'ui', 'strike', 'css', 'kn-strike-overrides.css'))
    a = ap.parse_args()
    css = open(a.css, encoding='utf-8').read()
    out, stats, restating = [], {'translate': 0, 'restated': 0}, False
    for sel, body in top_rules(css):
        ds = decls(body)
        tf = transform_of(dict(ds))
        if tf:
            out.append('%s{transform:%s}' % (sel, tf))
            stats['translate'] += 1
            restating = True
        elif restating:
            own = [v for k, v in ds if k == 'transform']
            if own:
                out.append('%s{transform:%s}' % (sel, own[-1]))
                stats['restated'] += 1
    for name, frames_ in keyframes_blocks(css):
        conv, changed = [], False
        for fsel, fbody in frames_:
            ds = decls(fbody)
            tf = transform_of(dict(ds))
            keep = ['%s:%s' % (k, v) for k, v in ds if k not in ('translate', 'scale', 'transform')]
            if tf:
                keep.append('transform:%s' % tf)
                changed = True
            elif 'transform' in dict(ds):
                keep.append('transform:%s' % dict(ds)['transform'])
            conv.append('%s{%s}' % (fsel, ';'.join(keep)))
        if changed:
            out.append('@keyframes %s{%s}' % (name, ''.join(conv)))
            stats['translate'] += 1
    text = open(a.out, encoding='utf-8').read() if os.path.exists(a.out) else ''
    head = text.split(BEGIN)[0].rstrip() + '\n\n' if BEGIN in text else text.rstrip() + '\n\n'
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(head + BEGIN + '\n' + '\n'.join(out) + '\n' + END + '\n')
    print('%(translate)d transform, %(restated)d restated' % stats)


if __name__ == '__main__':
    main()
