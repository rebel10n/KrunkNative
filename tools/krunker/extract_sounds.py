#!/usr/bin/env python3
"""Krunker sound-name table extractor: game.deob.js -> client/src/net/krunker_sounds.c.

The official server's "s" PLAYER_SOUND / "so" PLAY_SOUND / "sso" STOP_SOUND carry a sound as an
index into the client's sound-name array (game.playerSound: `sounds[i]` unless isAsset), the array
that starts ['spray', 'taunt_0', ...] (game.deob.js 10.0.3 :18253). Static parsing only: the array
literal is found by that anchor and read as a list of string literals; no Krunker JS is executed.

usage:
  python3 -I tools/krunker/extract_sounds.py SOURCE [--out client/src/net/krunker_sounds.c]
  python3 -I tools/krunker/extract_sounds.py SOURCE --check     the committed table is current?
SOURCE: game.deob.js (e.g. the one tools/krunker/extract_build.py reads).
"""
import argparse
import hashlib
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "client", "src", "net", "krunker_sounds.c")
ANCHOR = re.compile(r"""=\s*\[\s*['"]spray['"]\s*,\s*['"]taunt_0['"]""")
STRING = re.compile(r"""\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*(,|\])""")


def extract(text):
    m = ANCHOR.search(text)
    if not m:
        raise SystemExit("extract_sounds: anchor ['spray', 'taunt_0', ...] not found")
    i = text.index("[", m.start()) + 1
    names = []
    while True:
        s = STRING.match(text, i)
        if not s:
            raise SystemExit("extract_sounds: a non-string element at offset %d" % i)
        name = s.group(1) if s.group(1) is not None else s.group(2)
        if not re.fullmatch(r"[A-Za-z0-9_/\-.]{1,64}", name):
            raise SystemExit("extract_sounds: unexpected sound name %r" % name)
        names.append(name)
        i = s.end()
        if s.group(3) == "]":
            return names


def render(names, sha):
    rows = "".join('    "%s",\n' % n for n in names)
    return ("// GENERATED by tools/krunker/extract_sounds.py -- do not edit.\n"
            "// Regenerate: python3 -I tools/krunker/extract_sounds.py <game.deob.js>\n"
            "// The official client's sound-name array (game.deob.js 10.0.3 :18253, the one starting\n"
            "// ['spray', 'taunt_0', ...]): \"s\" / \"so\" / \"sso\" index it (client/include/krunker_sounds.h).\n"
            "// Source sha256: %s\n"
            "#include <krunker_sounds.h>\n"
            "#include <stddef.h>\n\n"
            "static const char *const k_names[%d] = {\n%s};\n\n"
            "const char *krunker_sound_name(const int index) {\n"
            "    return index >= 0 && (size_t) index < sizeof(k_names) / sizeof(k_names[0]) ? k_names[index] : NULL;\n"
            "}\n\n"
            "int krunker_sound_count(void) { return (int) (sizeof(k_names) / sizeof(k_names[0])); }\n") % (sha, len(names), rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("source")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = open(a.source, "rb").read()
    out = render(extract(data.decode("utf-8")), hashlib.sha256(data).hexdigest())
    if a.check:
        cur = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else ""
        if cur != out:
            print("extract_sounds: %s is stale" % a.out)
            return 1
        return 0
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(out)
    print("extract_sounds: %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
