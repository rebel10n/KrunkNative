#!/usr/bin/env python3
"""Krunker network sound table extractor: game.deob.js -> shared/src/rules/v10/network_sounds_v10.c.

config.networkSounds (deob-10.0.4.js:18263, the config key :19904) is the sound list Krunker puts
on the wire as an index: the server sends `networkSounds.indexOf(name)` in "s" PLAYER_SOUND / "so"
PLAY_SOUND / "sso" STOP_SOUND, the "6" GET_KILL kill sound and config.taunts' id, and the client
plays `networkSounds[i]` unless the message flags a user asset (shared/include/network_sounds.h).
It is the array literal that starts ['spray', 'taunt_0', ...]. Static parsing only: the literal is
found by that anchor and read as a list of string literals; no Krunker JS is executed.

Writes the C table, the TypeScript one of the v10 bridge (net-bridge/networkSounds.ts) and the test
fixture shared/tests/data/v10/networkSounds.json (the names in id order, what
shared/tests/network_sounds_test.c and net-bridge/v10Proxy.test.ts check the tables against).

usage:
  python3 -I tools/krunker/extract_sounds.py SOURCE [--out F] [--ts F] [--fixture F] [--cite deob-10.0.4.js]
  python3 -I tools/krunker/extract_sounds.py SOURCE --check     are the committed table and fixture current?
SOURCE: the decoded bundle, ~/.cache/kn-official/game-10.0.4.deob.js for v10.0.4.
"""
import argparse
import hashlib
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "shared", "src", "rules", "v10", "network_sounds_v10.c")
FIXTURE = os.path.join(ROOT, "shared", "tests", "data", "v10", "networkSounds.json")
TS_OUT = os.path.join(ROOT, "net-bridge", "networkSounds.ts")
ANCHOR = re.compile(r"""=\s*\[\s*['"]spray['"]\s*,\s*['"]taunt_0['"]""")
STRING = re.compile(r"""\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*(,|\])""")


def extract(text):
    """(names, line): the array's string literals and the 1-based line it opens on."""
    m = ANCHOR.search(text)
    if not m:
        raise SystemExit("extract_sounds: anchor ['spray', 'taunt_0', ...] not found")
    line = text.count("\n", 0, m.start()) + 1
    i = text.index("[", m.start()) + 1
    names = []
    while True:
        s = STRING.match(text, i)
        if not s:
            raise SystemExit("extract_sounds: a non-string element at offset %d" % i)
        name = s.group(1) if s.group(1) is not None else s.group(2)
        if not re.fullmatch(r"[A-Za-z0-9_/\-.]{1,64}", name):
            raise SystemExit("extract_sounds: unexpected sound name %r" % name)
        names.append(name)
        i = s.end()
        if s.group(3) == "]":
            return names, line


def render(names, sha, cite):
    rows = "".join('    /* %3d */ "%s",\n' % (i, n) for i, n in enumerate(names))
    return ("// GENERATED by tools/krunker/extract_sounds.py -- do not edit.\n"
            "// Regenerate: python3 -I tools/krunker/extract_sounds.py ~/.cache/kn-official/game-10.0.4.deob.js --cite deob-10.0.4.js\n"
            "// config.networkSounds (%s, %d names), in id order: the sound list Krunker sends as an\n"
            "// index (shared/include/network_sounds.h). Source sha256: %s\n"
            "#include <network_sounds.h>\n"
            "#include <string.h>\n\n"
            "const char *const g_network_sounds[] = {\n%s};\n\n"
            "const char *network_sound_name(const int id) {\n"
            "    return id >= 0 && id < NETWORK_SOUND_COUNT ? g_network_sounds[id] : NULL;\n"
            "}\n\n"
            "int network_sound_index(const char *name) {\n"
            "    for (int i = 0; name && i < NETWORK_SOUND_COUNT; i++) { // indexOf: the first match\n"
            "        if (!strcmp(g_network_sounds[i], name)) return i;\n"
            "    }\n"
            "    return -1;\n"
            "}\n") % (cite, len(names), sha, rows)


def render_ts(names, sha, cite):
    rows = "".join('  "%s", // %d\n' % (n, i) for i, n in enumerate(names))
    return ("\"use strict\";\n\n"
            "// GENERATED by tools/krunker/extract_sounds.py -- do not edit.\n"
            "// config.networkSounds (%s, %d names) in id order: the sound list v10 sends as an index in \"s\" /\n"
            "// \"so\" / \"sso\" (the C table is shared/include/network_sounds.h). Source sha256: %s\n\n"
            "export const NETWORK_SOUNDS: readonly string[] = Object.freeze([\n%s]);\n\n"
            "// networkSounds.indexOf(name): the first id with that name, -1 when the list has none.\n"
            "export function networkSoundIndex(name: string): number {\n"
            "  return NETWORK_SOUNDS.indexOf(name);\n"
            "}\n") % (cite, len(names), sha, rows)


def render_fixture(names, sha, cite):
    return json.dumps({"source": cite, "sha256": sha, "networkSounds": names}, indent=1) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("source")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--fixture", default=FIXTURE)
    ap.add_argument("--ts", default=TS_OUT)
    ap.add_argument("--cite", default="deob-10.0.4.js", help="the bundle's name in the citations")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = open(a.source, "rb").read()
    names, line = extract(data.decode("utf-8"))
    sha = hashlib.sha256(data).hexdigest()
    cite = "%s:%d" % (a.cite, line)
    outputs = [(a.out, render(names, sha, cite)), (a.ts, render_ts(names, sha, cite)), (a.fixture, render_fixture(names, sha, cite))]
    if a.check:
        stale = 0
        for path, text in outputs:
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if cur != text:
                print("extract_sounds: %s is stale" % path)
                stale = 1
        return stale
    for path, text in outputs:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("extract_sounds: %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
