#!/usr/bin/env python3
"""Generates client/src/editor/editor_data.c from the Krunker v3.1.1 editor sources.

    python3 -I tools/editor/gen_editor_data.py

The readable editor sources come from the source map of the v3.1.1 editor bundle
(public/js/src/editor.js.map, sourcesContent); they are extracted into
$KN_EDITOR_SRC (default /tmp/kn-editor-src/src) when missing. The dump_*.js
scripts next to this file load data/prefabs.js, config.js, data/modes.js,
data/classes.js, data/weapons.js and data/triggers.js under node with browser
stubs and print their data as JSON; this script writes

- the prefab table (name, label, default size, model scale, line colour, opacity,
  every boolean flag the editor GUI reads) as C structs, and
- the configuration lists the editor panels are built from (gameConfig,
  serverConfig, weaponConfig, modes, classes, weapons, textures, particles,
  emitter sounds, trigger events/actions, limits) as one JSON string parsed once
  at run time (editor_data_json()).
"""

import json
import re
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
KRUNKER = "/home/user/jails/kru/src/Krunker_v3.1.1/public"
SRC = os.environ.get("KN_EDITOR_SRC", "/tmp/kn-editor-src/src")
OUT = os.path.join(REPO, "client", "src", "editor", "editor_data.c")

# prefab boolean properties the editor reads (data/prefabs.js); EP_<UPPER> bits
FLAGS = [
    "editFaces", "editFog", "movingTexture", "hasHealth", "scalable", "editAmb", "editColor",
    "editEmissive", "editOpac", "editPen", "texturable", "assetTextures", "hasBorder",
    "canInterface", "canStretch", "canBeDynamic", "canWallJump", "gen", "genGeo", "editorGen",
    "tool", "tool2", "ai", "notTechnical", "notStyleable", "teamable", "customDirection",
    "optionalDirection", "boostable", "bounce", "edgeNoise", "hasSpin", "customScore",
    "interact", "interact2", "canUndo", "canTargetInterface", "objectiveLink", "light",
    "hasText", "complex", "custom", "noExport", "localOnly", "noCol", "noCollision",
    "forceCollision", "hideBoundingBox", "dontRound", "alwaysSee", "isCam", "fakeScale",
    "wireframe", "noDefault", "hasSound", "canTerrain", "isProp", "scaleWithSize",
    "doubleSide", "transparent", "emiss", "noTexture", "shootable",
]


# defaultSize of genGeo prefabs without one: the bounds of the geometry they generate
GENGEO_SIZES = {
    "SPAWN_POINT": [7, 11, 7],  # generateSpawn: generateCube(..., 7, 11, 7)
}


def extract_sources():
    if os.path.exists(os.path.join(SRC, "data", "prefabs.js")):
        return
    smap = os.path.join(KRUNKER, "js", "src", "editor.js.map")
    with open(smap, "r", encoding="utf-8") as fh:
        m = json.load(fh)
    root = os.path.dirname(SRC)
    for name, content in zip(m["sources"], m.get("sourcesContent") or []):
        if not content:
            continue
        rel = name.split("src/", 1)
        if len(rel) != 2:
            continue
        path = os.path.join(root, "src", rel[1])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)


def node_json(script):
    env = dict(os.environ, KN_EDITOR_SRC=SRC)
    out = subprocess.run(["node", os.path.join(HERE, script)], env=env, check=True,
                         capture_output=True, text=True, cwd="/tmp").stdout
    return json.loads(out)


def format_const_name(name):
    return " ".join(p[:1].upper() + p[1:].lower() for p in name.lower().split("_"))


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_float(v):
    r = repr(float(v))
    return r + "f" if ("." in r or "e" in r) else r + ".0f"


def model_size(prefab):
    """defaultSize of a model prefab: the bounds of its OBJ at prefab.scale (ObjectInstance.promises)."""
    src = prefab.get("gen") or ""
    m = re.search(r'"(models/[a-z_0-9]+\.obj)"', src)
    if not m:
        return None
    path = os.path.join(REPO, "assets", m.group(1))
    if not os.path.exists(path):
        return None
    lo, hi = [1e9] * 3, [-1e9] * 3
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith("v "):
                v = [float(x) for x in line.split()[1:4]]
                lo = [min(a, b) for a, b in zip(lo, v)]
                hi = [max(a, b) for a, b in zip(hi, v)]
    scale = prefab.get("scale") or 1
    return [round((b - a) * scale, 3) for a, b in zip(lo, hi)]


def main():
    extract_sources()
    prefabs = node_json("dump_prefabs.js")
    config = node_json("dump_config.js")
    data = node_json("dump_data.js")

    lines = [
        "// GENERATED by tools/editor/gen_editor_data.py from the Krunker v3.1.1 editor sources",
        "// (public/js/src/editor.js.map: data/prefabs.js, config.js, data/*.js). Do not edit.",
        "#include \"editor_data.h\"",
        "",
        "const EditorPrefab editor_prefabs[EDITOR_PREFAB_COUNT] = {",
    ]
    for p in prefabs["prefabs"]:
        flags = [("EP_" + f.upper()) for f in FLAGS if p.get(f)]
        size = p.get("defaultSize")
        computed = 0
        if not size and p["name"] in GENGEO_SIZES:
            size = GENGEO_SIZES[p["name"]]  # bounds of the genGeo cube (ObjectInstance.promises)
            computed = 2
        if not size:
            size = model_size(p)
            computed = 2 if size else 0
        line_col = p.get("lineCol")
        lines.append("    {%s, %s, {%s}, %d, %s, %d, %s, %s}," % (
            c_str(p["name"]), c_str(format_const_name(p["name"]) if p["name"] else ""),
            ", ".join(c_float(v) for v in (size or [1, 1, 1])), (computed or 1) if size else 0,
            c_float(p.get("scale", 1) or 1),
            line_col if line_col is not None else -1,
            c_float(p.get("opacity", 1) if p.get("opacity") is not None else 1),
            " | ".join(flags) if flags else "0",
        ))
    lines.append("};")
    lines.append("")
    lines.append("const char *const editor_textures[EDITOR_TEXTURE_COUNT] = {")
    lines.append("    " + ", ".join(c_str(t["name"]) for t in prefabs["textures"]) + ",")
    lines.append("};")
    lines.append("")

    blob = {
        "gameConfig": config["gameConfig"],
        "serverConfig": config["serverConfig"],
        "weaponConfig": config["weaponConfig"],
        "interfaceIDMax": config["interfaceIDMax"],
        "modes": data["modes"],
        "classes": data["classes"],
        "weapons": [{k: w.get(k) for k in ["name", "src"] + [c["varN"] for c in config["weaponConfig"]] if w.get(k) is not None}
                    for w in data["weapons"]],
        "particleIDS": data["particleIDS"],
        "emitterSounds": data["emitterSounds"],
        "particleBlending": data["particleBlending"],
        "triggers": data["triggers"],
        "limits": {k: data[k] for k in ["spawnLimit", "signLimit", "objectLimit", "objectColLimit"]},
        "defaults": {k: data[k] for k in ["shadowRes", "shadowDst", "lightDistance", "lightIntensity",
                                          "ambIntensity", "sunAngleX", "sunAngleY"]},
    }
    text = json.dumps(blob, separators=(",", ":"), ensure_ascii=True)
    lines.append("// the editor's configuration lists, parsed once by editor_data_json()")
    lines.append("const char editor_data_text[] =")
    for i in range(0, len(text), 100):
        lines.append("    " + c_str(text[i:i + 100]))
    lines.append(";")
    lines.append("")

    header_flags = []
    for i, f in enumerate(FLAGS):
        header_flags.append("#define EP_%-22s (1ull << %d)" % (f.upper(), i))
    flags_path = os.path.join(REPO, "client", "src", "editor", "editor_prefab_flags.h")
    with open(flags_path, "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by tools/editor/gen_editor_data.py: Krunker v3.1.1 data/prefabs.js flags.\n#pragma once\n\n")
        fh.write("#define EDITOR_PREFAB_COUNT %d\n#define EDITOR_TEXTURE_COUNT %d\n\n" % (len(prefabs["prefabs"]), len(prefabs["textures"])))
        fh.write("\n".join(header_flags) + "\n")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d prefabs, %d textures, %d bytes of config)" % (
        os.path.relpath(OUT, REPO), len(prefabs["prefabs"]), len(prefabs["textures"]), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
