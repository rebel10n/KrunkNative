-- 0200_matchmaker: cross-brain registry of brains, game server nodes and their
-- lobbies (v3.1.1 matchmaker/registry.ts, persisted so several brains share one
-- global view). Owner: svc-matchmaker (services/brain/federation.c).
--
-- Leader free: each brain writes only the rows of the game servers connected to
-- it (brain_id = itself) and refreshes heartbeat_at every brain.heartbeat_s.
-- Rows older than brain.node_ttl_s are ignored by readers and reaped by any brain.

CREATE TABLE mm_brains (
    brain_id     text PRIMARY KEY,
    region       text NOT NULL,
    public_url   text NOT NULL DEFAULT '',
    version      text NOT NULL DEFAULT '',
    started_at   timestamptz NOT NULL DEFAULT now(),
    heartbeat_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE mm_nodes (
    node_id      text PRIMARY KEY CHECK (node_id ~ '^[A-Za-z0-9_.-]{1,47}$'),
    brain_id     text NOT NULL,
    region       text NOT NULL,
    name         text NOT NULL DEFAULT '',
    public_host  text NOT NULL DEFAULT '',
    public_port  integer NOT NULL DEFAULT 0,
    web_url      text NOT NULL DEFAULT '',
    version      text NOT NULL DEFAULT '',
    max_players  integer NOT NULL DEFAULT 8,
    max_lobbies  integer NOT NULL DEFAULT 1,
    custom       boolean NOT NULL DEFAULT false,
    draining     boolean NOT NULL DEFAULT false,
    hello        jsonb NOT NULL DEFAULT '{}'::jsonb,
    connected_at timestamptz NOT NULL DEFAULT now(),
    heartbeat_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mm_nodes_brain_idx ON mm_nodes (brain_id);
CREATE INDEX mm_nodes_heartbeat_idx ON mm_nodes (heartbeat_at);

CREATE TABLE mm_lobbies (
    game_id      text PRIMARY KEY,               -- "<node_id>:<local_id>"
    node_id      text NOT NULL REFERENCES mm_nodes (node_id) ON DELETE CASCADE,
    local_id     text NOT NULL,
    region       text NOT NULL,
    players      integer NOT NULL DEFAULT 0,
    max_players  integer NOT NULL DEFAULT 8,
    custom       boolean NOT NULL DEFAULT false,
    protected    boolean NOT NULL DEFAULT false,
    mode         text NOT NULL DEFAULT '',
    map          text NOT NULL DEFAULT '',
    version      text NOT NULL DEFAULT '',
    tuple        jsonb NOT NULL,                 -- [gameId, region, players, max, meta]
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mm_lobbies_node_idx ON mm_lobbies (node_id);
CREATE INDEX mm_lobbies_region_idx ON mm_lobbies (region);

-- Seats handed out by seek-game (join tickets) that have not joined yet, so
-- parallel seeks on different brains do not overfill a lobby.
CREATE TABLE mm_reservations (
    jti          text PRIMARY KEY,
    game_id      text NOT NULL,
    brain_id     text NOT NULL,
    account_id   bigint,
    expires_at   timestamptz NOT NULL
);
CREATE INDEX mm_reservations_game_idx ON mm_reservations (game_id, expires_at);

-- Host-game requests routed to a game server owned by another brain.
CREATE TABLE mm_host_requests (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_brain   text NOT NULL,
    target_brain text NOT NULL,
    target_node  text NOT NULL,
    region       text NOT NULL DEFAULT '',
    config       jsonb NOT NULL DEFAULT '{}'::jsonb,
    host_account bigint,
    host_name    text,
    status       text NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'sent', 'done', 'failed')),
    result       jsonb,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mm_host_requests_target_idx ON mm_host_requests (target_brain, status);

-- Operator view: every lobby whose node is still heartbeating (30 s default TTL).
CREATE VIEW mm_live_lobbies AS
    SELECT l.game_id, l.region, n.brain_id, l.node_id, n.public_host, n.public_port,
           l.players, l.max_players, l.custom, l.mode, l.map, n.draining,
           n.heartbeat_at
      FROM mm_lobbies l JOIN mm_nodes n USING (node_id)
     WHERE n.heartbeat_at > now() - interval '30 seconds';
