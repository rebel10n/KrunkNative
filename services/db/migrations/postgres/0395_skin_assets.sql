-- 0395_skin_assets (PostgreSQL): the Skin Manager's files and Studios' skins (services/brain/skins.c, asset_upload.c,
-- db_studios.c).
--   custom_skins ids start at 1000000000 (shared/include/user_asset_path.h USER_ASSET_KN_ID_BASE): a skin's files are
--     "skins/<skinId>/<file>" (v10.0.7's game loads skins/<_id>/, _id = skinId, deob-10.0.7.js:120593, :173611), so a
--     Box Office skin's folder never names one of Krunker's map studio skins' folders (user_asset_rel_is_kn).
--   studio_skins: a custom skin assigned to a studio (POST /studios/:id/skins/import {custom_skin_id},
--     deob-10.0.7.js:27601-27625; the studio view's Skins tab, :138552, :138761-138800): a copy of the skin's name,
--     type, weapon, rarity and itemConfig at the import, csrc the custom skin whose skins/<csrc>/ folder holds its files
--     (setCustomSkins' thumbnail "/skins/" + csrc + "/thumbnail.png", :226227). Its id is the game's skin id (scripts'
--     setSkin / PAYMENTS.giveSkin take ids from 10000000, iïìíiîï), so ids start at 10000001. active: published (only
--     published skins are in the studio's games). Additive only.
SELECT setval(pg_get_serial_sequence('custom_skins', 'id'),
              GREATEST(999999999, (SELECT coalesce(max(id), 0) FROM custom_skins)));
CREATE TABLE studio_skins (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id      integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    custom_skin_id bigint NOT NULL,
    name           text NOT NULL,
    type           smallint NOT NULL DEFAULT 0,
    weapon         smallint NOT NULL DEFAULT 0,
    rarity         smallint NOT NULL DEFAULT 0,
    item_config    text NOT NULL DEFAULT '{}',
    active         smallint NOT NULL DEFAULT 0,
    created_by     integer REFERENCES accounts(id) ON DELETE SET NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX studio_skins_studio_skin_uq ON studio_skins (studio_id, custom_skin_id);
SELECT setval(pg_get_serial_sequence('studio_skins', 'id'), 10000000);
