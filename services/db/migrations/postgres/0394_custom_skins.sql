-- 0394_custom_skins (PostgreSQL): Krunker v10.0.7's Skin Manager records (the gapi skins.* client, deob-10.0.7.js:
-- 26551-26604: GET /skins?page&page_size&type&weapon&search, GET|PUT|DELETE /skins/:id, POST /skins,
-- POST /skins/:id/duplicate; the window, :124611-127559, opened from the sandbox menu's Skin Manager item) behind
-- kn_brain (services/brain/skins.c, P_CUSTOM_SKIN). A skin is its creator's: name, type (0 weapon .. 18 paint, the
-- General tab's list), weapon (1-based, for type 0), rarity (store.rarities index) and itemConfig, the JSON object
-- the Appearance and Advanced tabs edit (copyId, customTextures, glow, ...), kept as text. Additive only.
CREATE TABLE custom_skins (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name        text NOT NULL,
    type        smallint NOT NULL DEFAULT 0,
    weapon      smallint NOT NULL DEFAULT 0,
    rarity      smallint NOT NULL DEFAULT 0,
    item_config text NOT NULL DEFAULT '{}',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX custom_skins_owner_idx ON custom_skins (owner_id, id);
