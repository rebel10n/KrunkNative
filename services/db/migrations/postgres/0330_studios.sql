-- 0330_studios: Krunker v10.0.2's Studios, the teams of map and skin creators (v10 gapi /studios paths,
-- v10.js 27360-27520; the Studios window and the studio view, v10.js 137011-138440). A studio has one
-- owner (role 1) and members (role 2), up to 20 counting pending invites; invites expire after 14
-- days. Its games are published maps (one studio per map), its currencies are up to 5 per studio.
-- Monetization is an application record only: KrunkNative takes no payments, so an application
-- stays "pending" until a developer reviews it in the database (status approved / rejected /
-- revoked, review_note), and approval only sets studios.monetization. Owner:
-- services/brain/db_studios.c (procs, C on every driver), routes services/brain/studios.c.
-- Additive only.
CREATE TABLE studios (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 text NOT NULL,
    owner_id             integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    monetization         smallint NOT NULL DEFAULT 0,   -- 1: approved (v10 "monetization": true)
    monetization_blocked smallint NOT NULL DEFAULT 0,   -- 1: may never apply again (v10 "blocked")
    created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX studios_name_lower_uq ON studios (lower(name));
CREATE INDEX studios_owner_idx ON studios (owner_id);

CREATE TABLE studio_members (
    studio_id  integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    account_id integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    role       smallint NOT NULL DEFAULT 2,            -- 1 owner, 2 member (v10 role / my_role)
    joined_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (studio_id, account_id)
);
CREATE INDEX studio_members_account_idx ON studio_members (account_id);

CREATE TABLE studio_invites (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id  integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    account_id integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    invited_by integer REFERENCES accounts(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX studio_invites_uq ON studio_invites (studio_id, account_id);
CREATE INDEX studio_invites_account_idx ON studio_invites (account_id, expires_at);

CREATE TABLE studio_maps (
    map_id     integer PRIMARY KEY REFERENCES published_maps(map_id) ON DELETE CASCADE, -- one studio per game
    studio_id  integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    added_by   integer REFERENCES accounts(id) ON DELETE SET NULL,
    added_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX studio_maps_studio_idx ON studio_maps (studio_id);

CREATE TABLE studio_currencies (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id  integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    name       text NOT NULL,
    symbol     text NOT NULL,                          -- 2-4 upper-case letters, not KR / JNK / RP
    decimals   smallint NOT NULL DEFAULT 0,            -- 0..2
    active     smallint NOT NULL DEFAULT 1,            -- publish / unpublish
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX studio_currencies_symbol_uq ON studio_currencies (studio_id, symbol);

CREATE TABLE studio_monetization (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id    integer NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
    applicant_id integer REFERENCES accounts(id) ON DELETE SET NULL,
    description  text NOT NULL DEFAULT '',
    map_ids      text NOT NULL DEFAULT '[]',           -- JSON array of example game ids (<= 5)
    status       text NOT NULL DEFAULT 'pending',      -- pending, approved, rejected, revoked, cancelled
    review_note  text,
    reviewed_by  integer REFERENCES accounts(id) ON DELETE SET NULL,
    reviewed_at  timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX studio_monetization_studio_idx ON studio_monetization (studio_id, created_at DESC);
