-- 0101_social: follows, clans, chat, feed, mail, reports.  Owner: svc-accounts
-- (services/brain/social_data.c).  Shapes follow Krunker v3.1.1's social page
-- (src/social.js) and menu clan window (src/index.js windows[12]).

CREATE TABLE follows (
    follower_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    followee_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CHECK (follower_id <> followee_id)
);
CREATE INDEX follows_followee_idx ON follows (followee_id, created_at DESC);

-- players.player_followed / player_following stay in step with follows.
CREATE OR REPLACE FUNCTION kn_follows_count() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE players SET player_following = player_following + 1 WHERE player_id = NEW.follower_id;
        UPDATE players SET player_followed  = player_followed  + 1 WHERE player_id = NEW.followee_id;
        RETURN NEW;
    ELSE
        UPDATE players SET player_following = greatest(player_following - 1, 0) WHERE player_id = OLD.follower_id;
        UPDATE players SET player_followed  = greatest(player_followed  - 1, 0) WHERE player_id = OLD.followee_id;
        RETURN OLD;
    END IF;
END
$fn$;
CREATE TRIGGER follows_count AFTER INSERT OR DELETE ON follows
    FOR EACH ROW EXECUTE FUNCTION kn_follows_count();

-- Clans.  clan_name is Krunker's clan tag ([TAG], 1-4 characters by default).
-- Ranks follow config.clanRoles: 0 Recruit, 1 Soldier, 2 Captain, 3 Commander;
-- the creator (clan_playerid) is the leader.
CREATE TABLE clans (
    clan_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_name      text NOT NULL,
    clan_playerid  integer REFERENCES accounts(id) ON DELETE SET NULL,
    clan_score     bigint NOT NULL DEFAULT 0,
    clan_funds     bigint NOT NULL DEFAULT 0 CHECK (clan_funds >= 0),
    clan_rank      integer NOT NULL DEFAULT 0,    -- 1 = top clan (rainbow tag)
    clan_motd      text NOT NULL DEFAULT '',
    clan_discord   text,
    clan_region    integer NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX clans_name_lower_uq ON clans (lower(clan_name));
CREATE INDEX clans_score_idx ON clans (clan_score DESC);

CREATE TABLE clan_members (
    account_id  integer PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,  -- one clan per player
    clan_id     integer NOT NULL REFERENCES clans(clan_id) ON DELETE CASCADE,
    rank        integer NOT NULL DEFAULT 0,
    score       bigint  NOT NULL DEFAULT 0,      -- XP earned while in the clan
    kills       bigint  NOT NULL DEFAULT 0,
    deaths      bigint  NOT NULL DEFAULT 0,
    joined_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX clan_members_clan_idx ON clan_members (clan_id);

CREATE TABLE clan_requests (
    clan_id     integer NOT NULL REFERENCES clans(clan_id) ON DELETE CASCADE,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (clan_id, account_id)
);

CREATE TABLE clan_messages (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clan_id     integer NOT NULL REFERENCES clans(clan_id) ON DELETE CASCADE,
    sender_id   integer REFERENCES accounts(id) ON DELETE SET NULL,
    body        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX clan_messages_clan_idx ON clan_messages (clan_id, id DESC);

-- Direct chat ("chtb" / "ctd" / "ict").
CREATE TABLE chat_messages (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sender_id    integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    receiver_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    body         text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    read_at      timestamptz
);
CREATE INDEX chat_messages_pair_idx ON chat_messages (least(sender_id, receiver_id), greatest(sender_id, receiver_id), id DESC);
CREATE INDEX chat_messages_receiver_idx ON chat_messages (receiver_id, read_at);

-- Feed ("ps" / "com" / "gps" / "lps" / "dps" / "guf", page "feed").
CREATE TABLE feed_posts (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    author_id   integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    body        text NOT NULL,
    type        integer NOT NULL DEFAULT 0,
    link        text,
    link2       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);
CREATE INDEX feed_posts_author_idx ON feed_posts (author_id, id DESC);
CREATE INDEX feed_posts_recent_idx ON feed_posts (id DESC) WHERE deleted_at IS NULL;

CREATE TABLE feed_comments (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    post_id     bigint NOT NULL REFERENCES feed_posts(id) ON DELETE CASCADE,
    author_id   integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    body        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feed_comments_post_idx ON feed_comments (post_id, id);

CREATE TABLE feed_likes (
    post_id     bigint NOT NULL REFERENCES feed_posts(id) ON DELETE CASCADE,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, account_id)
);

-- Krunker mail (menu "kml" list / "rml" read / "gmc" unread count).
CREATE TABLE mail (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    sender      text NOT NULL DEFAULT 'Krunker',
    subject     text NOT NULL DEFAULT '',
    body        text NOT NULL DEFAULT '',
    kr          bigint NOT NULL DEFAULT 0,       -- attached KR (claimed on read)
    created_at  timestamptz NOT NULL DEFAULT now(),
    read_at     timestamptz
);
CREATE INDEX mail_account_idx ON mail (account_id, id DESC);

-- Player reports ("rpt") and hacker flags / verification audit ("flg" / "ver").
CREATE TABLE reports (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    reporter_id  integer REFERENCES accounts(id) ON DELETE SET NULL,
    target_id    integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    reason       text NOT NULL,
    details      text NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    handled_at   timestamptz
);
CREATE INDEX reports_target_idx ON reports (target_id, created_at DESC);

CREATE TABLE moderation_log (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_id    integer REFERENCES accounts(id) ON DELETE SET NULL,
    target_id   integer REFERENCES accounts(id) ON DELETE CASCADE,
    action      text NOT NULL,                  -- 'flag' | 'unflag' | 'verify' | 'unverify' | 'ban' | 'unban' | 'delete-creation' | ...
    detail      text,
    at          timestamptz NOT NULL DEFAULT now()
);
