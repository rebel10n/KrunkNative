-- 0341_double_xp (PostgreSQL): Krunker v10.0.2's double XP, as the brain applies it (services/brain/double_xp.h,
-- db_double_xp.c, double_xp_social.c). Replaces the timed-entitlement draft that never reached main.
--
-- v10's 2x XP is an end-screen offer after each match (doubleXPButton; "rqdxp" / "rrqdxp" doubles the
-- match's score). double_xp_offers keeps the last committed match per account: offered (1 when the match
-- counted and was not competitive), games (the account's games after it), xp (the match's XP credited)
-- and claimed_games (v10's lastDoubleAttempt). double_xp_claims records every claim (provider, the ad
-- proof: NULL for the placeholder). The class and raid-drop doubling follow v10's weekend schedules
-- (UTC); nothing is stored for them. Additive except kn_commit_stats / kn_account_json, which are
-- replaced with the same results plus the offer, the class schedule and the "dxp" object.
CREATE TABLE double_xp_offers (
    account_id    integer PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    offered       smallint NOT NULL DEFAULT 0,
    games         integer NOT NULL DEFAULT 0,
    xp            bigint NOT NULL DEFAULT 0,
    claimed_games integer NOT NULL DEFAULT 0
);

CREATE TABLE double_xp_claims (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    games      integer NOT NULL,
    xp         bigint NOT NULL,
    provider   text NOT NULL,
    ad_ref     text,
    claimed_at bigint NOT NULL
);
CREATE INDEX double_xp_claims_account_idx ON double_xp_claims (account_id, games);

-- The "dxp" object of kn_account_json: the offer of the last match (NULL when none is offered), and
-- the v10 schedules today (UTC): doubleClassXP (Saturday / Sunday of an even ISO week), doubleRaidDrops
-- (Saturday / Sunday).
CREATE OR REPLACE FUNCTION kn_dxp(p_id integer) RETURNS jsonb
LANGUAGE sql VOLATILE AS $fn$
    WITH t AS (SELECT clock_timestamp() AT TIME ZONE 'UTC' AS ts)
    SELECT jsonb_build_object(
        'offer', (SELECT jsonb_build_object('games', o.games, 'xp', o.xp,
                      'claimable', (p.player_games_played > 0 AND p.player_games_played % 3 = 0
                                    AND o.games = p.player_games_played AND o.claimed_games <> p.player_games_played))
                  FROM double_xp_offers o JOIN players p ON p.player_id = o.account_id
                  WHERE o.account_id = p_id AND o.offered = 1),
        'doubleClassXP', extract(dow FROM t.ts) IN (0, 6) AND extract(week FROM t.ts)::integer % 2 = 0,
        'doubleRaidDrops', extract(dow FROM t.ts) IN (0, 6))
    FROM t
$fn$;

CREATE OR REPLACE FUNCTION kn_account_json(p_id integer) RETURNS jsonb
LANGUAGE sql STABLE AS $fn$
    SELECT jsonb_build_object(
        'id', r.player_id,
        'username', r.player_name,
        'alias', coalesce(nullif(btrim(r.player_alias), ''), r.player_name),
        'score', r.player_score,
        'funds', r.player_funds,
        'clan', r.player_clan,
        'clan_rank', r.clan_rank,
        'clan_role', r.clan_role,
        'premium', r.player_premium,
        'dev', r.player_developer,
        'mod', r.player_moderator,
        'hack', r.player_hack,
        'featured', r.player_featured,
        'creator_badge', (SELECT p.creator_badge FROM players p WHERE p.player_id = r.player_id),
        'elo', r.player_elo, 'elo2', r.player_elo2, 'elo4', r.player_elo4,
        'chal', r.player_chal,
        'banned', (b.reason IS NOT NULL OR b.expires_at IS NOT NULL),
        'ban_reason', b.reason,
        'ban_expires', coalesce(extract(epoch FROM b.expires_at)::bigint, 0),
        'badges', coalesce((SELECT jsonb_agg(pb.badge ORDER BY pb.badge) FROM player_badges pb
                            WHERE pb.account_id = r.player_id), '[]'::jsonb),
        'dxp', kn_dxp(r.player_id),
        'data', jsonb_build_array(
            r.player_id, r.player_kills, r.player_wins, r.player_games_played,
            r.player_deaths, r.player_funds, r.player_score, r.player_clan,
            r.player_timeplayed, r.player_featured,
            coalesce((SELECT jsonb_agg(jsonb_build_object('ind', i.skin_id, 'cnt', i.count) ORDER BY i.skin_id)
                      FROM inventory i WHERE i.account_id = r.player_id AND i.count > 0), '[]'::jsonb),
            r.player_lastreward, r.player_developer, r.player_following,
            r.player_followed, 0, r.player_stats::jsonb, r.player_hack,
            r.partner_name, r.partner_approved, r.player_region,
            r.player_moderator, r.player_elo, r.player_elo2, r.player_elo4,
            r.player_chal, r.player_infected, r.player_premium,
            CASE WHEN r.player_2fa THEN 1 ELSE 0 END,
            coalesce(nullif(btrim(r.player_alias), ''), r.player_name),
            r.player_datenew, r.tw_twitchname, r.player_mapmod,
            r.clan_deaths, r.clan_kills, NULL, r.clan_regionid, r.clan_rank,
            r.jobrating, r.jobratingpositive))
    FROM player_rows r
    LEFT JOIN LATERAL kn_active_ban(r.player_id, NULL) b ON true
    WHERE r.player_id = p_id
$fn$;

-- kn_commit_stats (0103) with the v10 class schedule and the 2x XP offer (db_accounts.c run_commit_stats matches).
CREATE OR REPLACE FUNCTION kn_commit_stats(p jsonb, p_max_kr integer) RETURNS jsonb
LANGUAGE plpgsql AS $fn$
DECLARE
    v_id     integer := (p ->> 'id')::integer;
    v_kills  integer := greatest(coalesce((p ->> 'kills')::integer, 0), 0);
    v_deaths integer := greatest(coalesce((p ->> 'deaths')::integer, 0), 0);
    v_score  integer := greatest(coalesce((p ->> 'score')::integer, 0), 0);
    v_base   bigint  := least(greatest(coalesce((p ->> 'xp')::bigint, (p ->> 'score')::bigint, 0), 0), 2147483647);
    v_comp   boolean := coalesce((p ->> 'comp')::numeric, 0) <> 0;
    v_ts     timestamp := clock_timestamp() AT TIME ZONE 'UTC';
    v_dcl    boolean;
    v_cls    bigint;
    v_won    boolean := coalesce((p ->> 'won')::numeric, 0) <> 0;
    v_games  integer := greatest(coalesce((p ->> 'games')::integer, 0), 0);
    v_time   bigint  := greatest(coalesce((p ->> 'time_ms')::bigint, 0), 0);
    v_kr     integer := least(greatest(coalesce((p ->> 'kr')::integer, 0), 0), greatest(p_max_kr, 0));
    v_class  integer := (p ->> 'class')::integer;
    v_stats  jsonb   := CASE WHEN jsonb_typeof(p -> 'stats') = 'object' THEN p -> 'stats' ELSE '{}'::jsonb END;
    v_match  text    := coalesce(nullif(p ->> 'match', ''), 'nomatch:' || gen_random_uuid()::text);
    v_clan   integer;
BEGIN
    -- v10 isDoubleClassXP, fixed when the match started: the game server sends it per round ("classDouble");
    -- without it (an older server) the schedule at the commit: Saturday and Sunday (UTC) of an even ISO week
    v_dcl := CASE WHEN (p ->> 'classDouble') IS NOT NULL THEN (p ->> 'classDouble')::numeric <> 0
                  ELSE extract(dow FROM v_ts) IN (0, 6) AND extract(week FROM v_ts)::integer % 2 = 0 END;
    v_cls := least(v_base * (CASE WHEN v_dcl THEN 2 ELSE 1 END), 2147483647);
    IF v_id IS NULL OR NOT EXISTS (SELECT 1 FROM players WHERE player_id = v_id) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Account not found.';
    END IF;
    INSERT INTO match_results (match_id, account_id, server, region, map, mode, class_id, kills, deaths,
                               score, won, games, time_ms, kr, stats)
    VALUES (v_match, v_id, p ->> 'server', p ->> 'region', p ->> 'map', p ->> 'mode', v_class,
            v_kills, v_deaths, v_score, v_won, v_games, v_time, v_kr, v_stats)
    ON CONFLICT (match_id, account_id) DO NOTHING;
    IF NOT FOUND THEN
        RETURN kn_account_json(v_id) || jsonb_build_object('kr_awarded', 0, 'duplicate', 1);
    END IF;
    IF v_class IS NOT NULL AND v_class >= 0 THEN
        v_stats := v_stats || jsonb_build_object('c' || v_class, v_cls);
    END IF;
    UPDATE players SET
        player_kills        = player_kills + v_kills,
        player_deaths       = player_deaths + v_deaths,
        player_wins         = player_wins + CASE WHEN v_won THEN 1 ELSE 0 END,
        player_games_played = player_games_played + v_games,
        player_score        = player_score + v_base,
        player_timeplayed   = player_timeplayed + v_time,
        player_funds        = player_funds + v_kr,
        player_stats        = kn_jsonb_add(player_stats, v_stats),
        player_region       = coalesce((p ->> 'region_index')::integer, player_region),
        updated_at          = now()
    WHERE player_id = v_id;
    IF v_kr > 0 THEN
        INSERT INTO kr_transactions (account_id, amount, source, ref) VALUES (v_id, v_kr, 'reward', v_match);
    END IF;
    UPDATE clan_members SET score = score + v_base, kills = kills + v_kills, deaths = deaths + v_deaths
    WHERE account_id = v_id RETURNING clan_id INTO v_clan;
    IF v_clan IS NOT NULL THEN
        UPDATE clans SET clan_score = clan_score + v_base WHERE clan_id = v_clan;
        UPDATE players SET player_clankills = player_clankills + v_kills,
                           player_clandeaths = player_clandeaths + v_deaths WHERE player_id = v_id;
    END IF;
    -- v10 end-screen 2x XP offer: the match just played, when it counted (not a competitive game)
    INSERT INTO double_xp_offers (account_id, offered, games, xp)
    VALUES (v_id, CASE WHEN v_games > 0 AND NOT v_comp THEN 1 ELSE 0 END,
            (SELECT player_games_played FROM players WHERE player_id = v_id), v_base)
    ON CONFLICT (account_id) DO UPDATE SET offered = EXCLUDED.offered, games = EXCLUDED.games, xp = EXCLUDED.xp;
    RETURN kn_account_json(v_id) || jsonb_build_object('kr_awarded', v_kr, 'duplicate', 0);
END
$fn$;
