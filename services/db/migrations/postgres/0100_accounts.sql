-- 0100_accounts: credentials, profiles (Krunker v3.1.1 qs_player), sessions, login
-- audit / brute-force lockout, bans, alias history.  Owner: svc-accounts
-- (services/brain/accounts.c).  Column names of `players` follow v3.1.1's
-- qs_player / get_qs_playerdata so rows map 1:1 onto src/data/account.js and the
-- social page's profile/leaderboard rows (doc/backend.md "Accounts & social").

-- Sum the numeric members of b into a (Krunker stats objects: {"c0":120,"hs":3,...}).
-- Non-numeric members of b replace a's value; non-numeric members of a are kept.
CREATE OR REPLACE FUNCTION kn_jsonb_add(a jsonb, b jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $fn$
    SELECT coalesce(a, '{}'::jsonb) || coalesce((
        SELECT jsonb_object_agg(k,
            CASE WHEN jsonb_typeof(v) = 'number'
                      AND jsonb_typeof(coalesce(a -> k, '0'::jsonb)) = 'number'
                 THEN to_jsonb(coalesce((a ->> k)::numeric, 0) + (v #>> '{}')::numeric)
                 ELSE v END)
        FROM jsonb_each(coalesce(b, '{}'::jsonb)) AS t(k, v)), '{}'::jsonb)
$fn$;

CREATE TABLE accounts (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       text NOT NULL CHECK (length(username) BETWEEN 1 AND 32),
    password_hash  text NOT NULL,                 -- kn_password_hash (PHC string)
    email          text,
    birthday       date,
    referral       text,                          -- ["a",0,[name,pass,ref]]
    created_at     timestamptz NOT NULL DEFAULT now(),
    created_ip     text,
    last_login_at  timestamptz,
    last_login_ip  text,
    twofa_secret   text,                          -- base32 TOTP secret when 2FA is on
    settings       text,                          -- "uploadS" settings blob (getS -> loadS)
    settings_at    timestamptz
);
CREATE UNIQUE INDEX accounts_username_lower_uq ON accounts (lower(username));

-- One row per account (player_id == accounts.id).
CREATE TABLE players (
    player_id                 integer PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    player_alias              text,               -- premium display name ("nme")
    player_kills              bigint  NOT NULL DEFAULT 0,
    player_deaths             bigint  NOT NULL DEFAULT 0,
    player_wins               bigint  NOT NULL DEFAULT 0,
    player_games_played       bigint  NOT NULL DEFAULT 0,
    player_score              bigint  NOT NULL DEFAULT 0,   -- XP; level = max(1, floor(0.03*sqrt(score)))
    player_timeplayed         bigint  NOT NULL DEFAULT 0,   -- ms
    player_funds              bigint  NOT NULL DEFAULT 0 CHECK (player_funds >= 0),  -- KR
    player_stats              jsonb   NOT NULL DEFAULT '{}'::jsonb,  -- {"c<class>":xp, hs, wb, mk, fk, n, tmk, s, h, flg, ...}
    player_lastreward         bigint  NOT NULL DEFAULT 0,
    player_elo                integer NOT NULL DEFAULT 0,
    player_elo2               integer NOT NULL DEFAULT 0,
    player_elo4               integer NOT NULL DEFAULT 0,
    player_chal               integer NOT NULL DEFAULT 0,
    player_region             integer NOT NULL DEFAULT 0,   -- config.socialRegions index of the last game
    player_premium            integer NOT NULL DEFAULT 0,   -- premiumT
    player_type               integer NOT NULL DEFAULT 0,
    player_developer          smallint NOT NULL DEFAULT 0,
    player_moderator          smallint NOT NULL DEFAULT 0,
    player_mapmod             smallint NOT NULL DEFAULT 0,
    player_featured           smallint NOT NULL DEFAULT 0,  -- verified tick ("ver")
    player_hack               smallint NOT NULL DEFAULT 0,  -- flagged hacker ("flg")
    player_infected           smallint NOT NULL DEFAULT 0,  -- virus event
    player_notrade            smallint NOT NULL DEFAULT 0,
    player_followed           integer NOT NULL DEFAULT 0,   -- followers (maintained by trigger)
    player_following          integer NOT NULL DEFAULT 0,   -- follows   (maintained by trigger)
    player_clankills          bigint  NOT NULL DEFAULT 0,
    player_clandeaths         bigint  NOT NULL DEFAULT 0,
    partner_name              text,
    partner_approved          integer NOT NULL DEFAULT 0,
    tw_twitchname             text,
    jobrating                 integer NOT NULL DEFAULT 0,
    jobratingpositive         integer NOT NULL DEFAULT 0,
    updated_at                timestamptz NOT NULL DEFAULT now()
);
-- Leaderboards (config.leaderQueries) read these orderings.
CREATE INDEX players_score_idx     ON players (player_score DESC);
CREATE INDEX players_kills_idx     ON players (player_kills DESC);
CREATE INDEX players_wins_idx      ON players (player_wins DESC);
CREATE INDEX players_time_idx      ON players (player_timeplayed DESC);
CREATE INDEX players_funds_idx     ON players (player_funds DESC);
CREATE INDEX players_elo_idx       ON players (player_elo DESC);
CREATE INDEX players_elo2_idx      ON players (player_elo2 DESC);
CREATE INDEX players_elo4_idx      ON players (player_elo4 DESC);
CREATE INDEX players_chal_idx      ON players (player_chal DESC);
CREATE INDEX players_followed_idx  ON players (player_followed DESC);
CREATE INDEX players_region_idx    ON players (player_region);

-- Session tokens: the 32-hex token from the "a" reply, stored as sha256.
CREATE TABLE sessions (
    token_hash    bytea PRIMARY KEY,
    account_id    integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    ip            text,
    origin        text                         -- 'social' | 'game' | 'http'
);
CREATE INDEX sessions_account_idx ON sessions (account_id);
CREATE INDEX sessions_expires_idx ON sessions (expires_at);

-- v3.1.1 qs_playerlogin_faillog / qs_playerloginfailure_block / qs_playerlogin2.
CREATE TABLE login_failures (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username   text NOT NULL,
    ip         text NOT NULL,
    at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX login_failures_name_ip_idx ON login_failures (lower(username), ip, at);

CREATE TABLE login_ip_blocks (
    ip          text PRIMARY KEY,
    failures    integer NOT NULL DEFAULT 0,
    whitelist   boolean NOT NULL DEFAULT false,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE login_audit (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    ip          text,
    via         text,                         -- 'password' | 'register' | 'token'
    at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX login_audit_account_idx ON login_audit (account_id, at DESC);

-- Account and IP bans (v3.1.1 qs_userblacklist + punishments). expires_at NULL = permanent.
CREATE TABLE bans (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id  integer REFERENCES accounts(id) ON DELETE CASCADE,
    ip          text,
    reason      text NOT NULL DEFAULT '',
    created_by  integer REFERENCES accounts(id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz,
    revoked_at  timestamptz,
    CHECK (account_id IS NOT NULL OR ip IS NOT NULL)
);
CREATE INDEX bans_account_idx ON bans (account_id) WHERE revoked_at IS NULL;
CREATE INDEX bans_ip_idx      ON bans (ip)         WHERE revoked_at IS NULL;

-- Display-name changes ("nme", premium) and username renames by staff.
CREATE TABLE name_changes (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind        text NOT NULL,                -- 'alias' | 'username'
    old_name    text,
    new_name    text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX name_changes_account_idx ON name_changes (account_id, at DESC);

-- Per-match stats commits from game servers (op "stats"). (match_id, account_id)
-- makes retries idempotent; also the profile's recent-games history.
CREATE TABLE match_results (
    match_id    text NOT NULL,
    account_id  integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    server      text,
    region      text,
    map         text,
    mode        text,
    class_id    integer,
    kills       integer NOT NULL DEFAULT 0,
    deaths      integer NOT NULL DEFAULT 0,
    score       integer NOT NULL DEFAULT 0,
    won         boolean NOT NULL DEFAULT false,
    games       integer NOT NULL DEFAULT 0,
    time_ms     bigint  NOT NULL DEFAULT 0,
    kr          integer NOT NULL DEFAULT 0,
    stats       jsonb   NOT NULL DEFAULT '{}'::jsonb,
    at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (match_id, account_id)
);
CREATE INDEX match_results_account_idx ON match_results (account_id, at DESC);

-- KR ledger (v3.1.1 qs_sale_transactions): rewards, gifts, market, admin.
CREATE TABLE kr_transactions (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id   integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    amount       bigint NOT NULL,             -- signed delta
    source       text NOT NULL,               -- 'reward' | 'gift-in' | 'gift-out' | 'market-sale' | 'market-buy' | 'market-fee' | 'quicksell' | 'challenge' | 'admin' | 'starting'
    ref          text,                        -- match id, listing id, peer id ...
    note         text,
    at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX kr_transactions_account_idx ON kr_transactions (account_id, at DESC);
